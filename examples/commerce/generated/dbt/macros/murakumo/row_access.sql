{#- Generated by Murakumo. Row-access policies (row_access on a table), set after it is built:
    re-creating a table drops its policies. Snowflake only; elsewhere it does nothing. -#}
{% macro murakumo_row_access(policy, column, condition) -%}
  {%- if target.type == 'snowflake' and execute -%}
    {%- set schema = target.database ~ '.governance' -%}
    {%- set name = schema ~ '.' ~ policy -%}
    {%- do run_query('create schema if not exists ' ~ schema) -%}
    {%- do run_query('create row access policy if not exists ' ~ name ~ ' as (val string) returns boolean -> ' ~ condition) -%}
    {%- do run_query('alter row access policy ' ~ name ~ ' set body -> ' ~ condition) -%}
    {#- An incremental table keeps its policy between builds: take it off before setting it again. -#}
    {%- do run_query('alter table ' ~ this ~ ' drop all row access policies') -%}
    {%- do run_query('alter table ' ~ this ~ ' add row access policy ' ~ name ~ ' on (' ~ column ~ ')') -%}
  {%- endif -%}
{%- endmacro %}
