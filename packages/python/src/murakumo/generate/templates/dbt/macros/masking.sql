{#- Generated by Murakumo. Masking policies (governance.masking), set on a mart's columns after it is
    built: re-creating a table drops its policies. Snowflake only; elsewhere it does nothing. -#}
{% macro murakumo_masking_body(rule, roles) -%}
  {%- set masks = {
      'redact': "'***'",
      'hash': 'sha2(val)',
      'null': 'null',
      'partial': "case when length(val) <= 4 then '***' else repeat('*', length(val) - 4) || right(val, 4) end",
  } -%}
  {%- if roles -%}
    case when {% for role in roles %}{% if not loop.first %} or {% endif %}is_role_in_session('{{ role | upper }}'){% endfor %} then val else {{ masks[rule] }} end
  {%- else -%}
    {{ masks[rule] }}
  {%- endif -%}
{%- endmacro %}

{% macro murakumo_masking(columns, roles) -%}
  {%- if target.type == 'snowflake' and execute -%}
    {%- set schema = target.database ~ '.governance' -%}
    {%- do run_query('create schema if not exists ' ~ schema) -%}
    {%- for rule in columns.values() | unique -%}
      {%- set policy = schema ~ '.murakumo_mask_' ~ rule -%}
      {%- set body = murakumo_masking_body(rule, roles) -%}
      {%- do run_query('create masking policy if not exists ' ~ policy ~ ' as (val string) returns string -> ' ~ body) -%}
      {%- do run_query('alter masking policy ' ~ policy ~ ' set body -> ' ~ body) -%}
    {%- endfor -%}
    {%- for column, rule in columns.items() -%}
      {%- do run_query('alter table ' ~ this ~ ' modify column ' ~ column ~ ' set masking policy ' ~ schema ~ '.murakumo_mask_' ~ rule ~ ' force') -%}
    {%- endfor -%}
  {%- endif -%}
{%- endmacro %}
