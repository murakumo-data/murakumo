{#- Generated by Murakumo. The run log: every dbt run records itself, its models and its tests
    in the audit schema, beside the tables it builds (with MURAKUMO_SCHEMA_PREFIX, in that
    environment's own audit schema). Loaders write row_counts the same way.

    audit.run_log      one row per run: when, which schedule, who, how it ended
    audit.model_runs   one row per model or snapshot: rows, seconds, status
    audit.dq_results   one row per test: passed or failed, and how many rows failed
    audit.row_counts   one row per raw table and load: rows ingested and rejected
    audit.daily_summary  per day: runs, rows ingested and rejected, failed models and tests -#}

{% macro murakumo_audit_schema() -%}
    {{ env_var('MURAKUMO_SCHEMA_PREFIX', '') }}audit
{%- endmacro %}

{% macro murakumo_audit_qualified_schema() -%}
    {%- if target.type in ('duckdb', 'postgres', 'redshift') -%}
        {{ murakumo_audit_schema() }}
    {%- else -%}
        {{ target.database }}.{{ murakumo_audit_schema() }}
    {%- endif -%}
{%- endmacro %}

{% macro murakumo_audit_relation(name) -%}
    {{ murakumo_audit_qualified_schema() }}.{{ name }}
{%- endmacro %}

{% macro murakumo_audit_setup() %}
    {%- set text = dbt.type_string() -%}
    {%- set stamp = dbt.type_timestamp() -%}
    {%- set number = dbt.type_bigint() -%}
    {%- set decimal = dbt.type_float() -%}
    {%- set statements = [] -%}
    {%- do statements.append("create schema if not exists " ~ murakumo_audit_qualified_schema()) -%}
    {%- set ddl -%}
    create table if not exists {{ murakumo_audit_relation('run_log') }} (
        run_id {{ text }}, engine {{ text }}, environment {{ text }}, schedule {{ text }}, invoked_by {{ text }},
        started_at {{ stamp }}, finished_at {{ stamp }}, status {{ text }},
        models_ok {{ number }}, models_failed {{ number }}, tests_passed {{ number }}, tests_failed {{ number }}
    )
    ;;
    create table if not exists {{ murakumo_audit_relation('model_runs') }} (
        run_id {{ text }}, model {{ text }}, kind {{ text }}, status {{ text }},
        rows_affected {{ number }}, rows_in_table {{ number }}, seconds {{ decimal }}, message {{ text }},
        finished_at {{ stamp }}
    )
    ;;
    create table if not exists {{ murakumo_audit_relation('dq_results') }} (
        run_id {{ text }}, test {{ text }}, model {{ text }}, column_name {{ text }}, status {{ text }},
        failures {{ number }}, severity {{ text }}, finished_at {{ stamp }}
    )
    ;;
    create table if not exists {{ murakumo_audit_relation('row_counts') }} (
        run_id {{ text }}, source {{ text }}, table_name {{ text }}, batch_id {{ text }},
        rows_ingested {{ number }}, rows_rejected {{ number }}, reason {{ text }}, loaded_at {{ stamp }}
    )
    ;;
    create or replace view {{ murakumo_audit_relation('daily_summary') }} as
    with runs as (
        select cast(started_at as date) as day, count(*) as runs,
               sum(models_failed) as models_failed, sum(tests_failed) as tests_failed
        from {{ murakumo_audit_relation('run_log') }} group by 1
    ), loads as (
        select cast(loaded_at as date) as day,
               sum(rows_ingested) as rows_ingested, sum(rows_rejected) as rows_rejected
        from {{ murakumo_audit_relation('row_counts') }} group by 1
    )
    select coalesce(runs.day, loads.day) as day,
           coalesce(runs.runs, 0) as runs,
           coalesce(loads.rows_ingested, 0) as rows_ingested,
           coalesce(loads.rows_rejected, 0) as rows_rejected,
           coalesce(runs.models_failed, 0) as models_failed,
           coalesce(runs.tests_failed, 0) as tests_failed
    from runs full outer join loads on runs.day = loads.day
    {%- endset -%}
    {#- One statement at a time: some warehouses (Snowflake) run only one per call. -#}
    {%- for statement in statements + ddl.split(';;') -%}
        {%- if statement.strip() -%}{%- do run_query(statement) -%}{%- endif -%}
    {%- endfor -%}
{% endmacro %}

{% macro murakumo_audit_text(value) -%}
    {%- if value is none -%}null{%- else -%}'{{ (value | string)[:1000] | replace("'", "''") }}'{%- endif -%}
{%- endmacro %}

{% macro murakumo_audit_number(value) -%}
    {%- if value is none or value == '' -%}null{%- else -%}{{ value }}{%- endif -%}
{%- endmacro %}

{% macro murakumo_audit(results) %}
    {%- set stamp = dbt.type_timestamp() -%}
    {%- set now = "cast(" ~ dbt.current_timestamp() ~ " as " ~ stamp ~ ")" -%}
    {%- set models = [] -%}
    {%- set tests = [] -%}
    {%- for result in results -%}
        {%- set node = result.node -%}
        {%- if node.resource_type in ('model', 'snapshot', 'seed') -%}
            {%- set rows = (result.adapter_response or {}).get('rows_affected') -%}
            {#- How many rows the table holds now (views are left out: counting one runs its query). -#}
            {%- set in_table = none -%}
            {%- if result.status == 'success' and node.config.materialized != 'view' and node.relation_name -%}
                {%- set in_table = run_query("select count(*) from " ~ node.relation_name).columns[0].values()[0] -%}
            {%- endif -%}
            {%- do models.append(
                "(" ~ murakumo_audit_text(invocation_id) ~ ", " ~ murakumo_audit_text(node.name) ~ ", "
                ~ murakumo_audit_text(node.resource_type) ~ ", " ~ murakumo_audit_text(result.status) ~ ", "
                ~ murakumo_audit_number(rows if rows is not none and rows >= 0 else none) ~ ", "
                ~ murakumo_audit_number(in_table) ~ ", "
                ~ murakumo_audit_number(result.execution_time) ~ ", "
                ~ murakumo_audit_text(result.message) ~ ", " ~ now ~ ")"
            ) -%}
        {%- elif node.resource_type == 'test' -%}
            {%- set attached = node.attached_node.split('.')[-1] if node.attached_node else none -%}
            {%- do tests.append(
                "(" ~ murakumo_audit_text(invocation_id) ~ ", " ~ murakumo_audit_text(node.name) ~ ", "
                ~ murakumo_audit_text(attached) ~ ", " ~ murakumo_audit_text(node.column_name) ~ ", "
                ~ murakumo_audit_text(result.status) ~ ", " ~ murakumo_audit_number(result.failures) ~ ", "
                ~ murakumo_audit_text(node.config.severity) ~ ", " ~ now ~ ")"
            ) -%}
        {%- endif -%}
    {%- endfor -%}
    {%- set failed_models = results | selectattr('node.resource_type', 'in', ['model', 'snapshot', 'seed'])
        | selectattr('status', 'in', ['error', 'skipped']) | list | length -%}
    {%- set ok_models = models | length - failed_models -%}
    {%- set failed_tests = results | selectattr('node.resource_type', 'equalto', 'test')
        | selectattr('status', 'in', ['fail', 'error']) | list | length -%}
    {%- set passed_tests = tests | length - failed_tests -%}
    {%- set status = 'failed' if failed_models or failed_tests else 'success' -%}
    {%- set run_log -%}
    insert into {{ murakumo_audit_relation('run_log') }} values (
        {{ murakumo_audit_text(invocation_id) }}, 'dbt', {{ murakumo_audit_text(target.name) }},
        {{ murakumo_audit_text(env_var('MURAKUMO_SCHEDULE', '')) }},
        {{ murakumo_audit_text(env_var('MURAKUMO_INVOKED_BY', env_var('USER', ''))) }},
        cast({{ murakumo_audit_text(run_started_at.strftime('%Y-%m-%d %H:%M:%S')) }} as {{ stamp }}), {{ now }},
        '{{ status }}', {{ ok_models }}, {{ failed_models }}, {{ passed_tests }}, {{ failed_tests }}
    )
    {%- endset -%}
    {%- do run_query(run_log) -%}
    {%- if models -%}
        {%- do run_query("insert into " ~ murakumo_audit_relation('model_runs') ~ " values " ~ models | join(', ')) -%}
    {%- endif -%}
    {%- if tests -%}
        {%- do run_query("insert into " ~ murakumo_audit_relation('dq_results') ~ " values " ~ tests | join(', ')) -%}
    {%- endif -%}
    {%- if target.type not in ('duckdb', 'bigquery') -%}{%- do run_query('commit') -%}{%- endif -%}
{% endmacro %}
