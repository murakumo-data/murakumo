"""The project as plain SQL: scripts that build it without dbt, in the order they must run.

The scripts come from the same dbt SQL `generate` writes, rendered a second time with Murakumo's
own ``source()``, ``ref()``, ``this`` and ``is_incremental()`` in place of dbt's, so they cannot
drift from the dbt project. dbt's own behaviour is written out as statements:

- views and tables are re-created on every run;
- an incremental model is created once with every row, then each run puts its new rows (those
  past the watermark) into a work table, deletes the rows they replace (same key) and inserts them;
- an SCD2 snapshot closes the current version of each key whose columns changed and inserts a
  new current version, keeping ``dbt_valid_from`` and ``dbt_valid_to`` as dbt does;
- every test is a query that returns the rows that fail it.

    00_landing.sql                   schemas and landing tables (safe to run again)
    01_staging__stg_erp__orders.sql  then one script per model, in dependency order
    ...
    tests/<model>.sql                one query per test; any rows returned are failures
"""

from __future__ import annotations

import re
from typing import Any

import sqlglot
from jinja2 import Environment, StrictUndefined
from sqlglot import exp

from murakumo.generate.ddl import DDL
from murakumo.generate.plan import Plan, Test, quote_identifier
from murakumo.manifest import Warehouse

HEADER = "-- Generated by Murakumo for {warehouse}: the project as plain SQL, without dbt.\n"
LAYER_SCHEMAS = {"staging": "staging", "intermediate": "intermediate", "marts": "marts", "semantic": "semantic"}
SNAPSHOT_SCHEMA = "snapshots"
_REF = re.compile(r"ref\('([^']+)'\)")
# T-SQL has no CREATE OR REPLACE TABLE; PostgreSQL and Redshift have it only for views.
_DROP_THEN_CREATE = (Warehouse.POSTGRES, Warehouse.REDSHIFT, Warehouse.FABRIC, Warehouse.SYNAPSE)


class Plain:
    def __init__(self, plan: Plan, dbt_files: dict[str, str]):
        self.plan = plan
        self.files = dbt_files
        self.target = plan.target
        self.dialect = plan.target.dialect
        self.warehouse = plan.target.warehouse
        self.schemas: dict[str, str] = {}  # model or snapshot -> schema
        for model in plan.models:
            self.schemas[model.name] = LAYER_SCHEMAS.get(model.layer, model.layer)
        for snapshot in plan.snapshots:
            self.schemas[snapshot.name] = SNAPSHOT_SCHEMA
        self.groups = {g.name: g.schema for g in plan.sources}

    # names --------------------------------------------------------------------------------------

    def q(self, name: str) -> str:
        return quote_identifier(name, self.dialect)

    def relation(self, name: str) -> str:
        return f"{self.q(self.schemas[name])}.{self.q(name)}"

    def source(self, group: str, table: str) -> str:
        return f"{self.q(self.groups[group])}.{self.q(table)}"

    def sql(self, text: str) -> str:
        """A DuckDB-dialect statement in the target's dialect."""
        if self.dialect == "duckdb":
            return text
        return ";\n".join(s for s in sqlglot.transpile(text, read="duckdb", write=self.dialect, pretty=True))

    def record_hash(self, columns: list[str], alias: str) -> str:
        """``murakumo_record_hash``: an md5 of every column, as text, joined with |."""
        parts: list[exp.Expression] = []
        for index, column in enumerate(columns):
            reference = sqlglot.parse_one(f"{alias}.{column}", read=self.dialect)
            parts.append(exp.Coalesce(this=exp.cast(reference, "varchar"), expressions=[exp.Literal.string("")]))
            if index < len(columns) - 1:
                parts.append(exp.Literal.string("|"))
        return exp.MD5(this=exp.Concat(expressions=parts)).sql(dialect=self.dialect)

    # rendering ----------------------------------------------------------------------------------

    def select(self, model, incremental: bool = False) -> str:
        """The model's select statement: its dbt SQL with dbt's functions resolved."""
        path = f"models/{model.folder}/{model.name}.sql"
        text = "\n".join(line for line in self.files[path].splitlines() if not line.startswith("-- Generated by"))
        env = Environment(undefined=StrictUndefined, keep_trailing_newline=False)
        rendered = env.from_string(text).render(
            source=self.source,
            ref=self.relation,
            this=self.relation(model.name),
            config=lambda **_: "",
            is_incremental=lambda: incremental,
            murakumo_record_hash=self.record_hash,
        )
        return re.sub(r"\n{3,}", "\n\n", rendered).strip()

    def create(self, kind: str, name: str, select: str) -> str:
        target = self.relation(name)
        if kind == "view":
            keyword = (
                "CREATE OR ALTER VIEW"
                if self.warehouse in (Warehouse.FABRIC, Warehouse.SYNAPSE)
                else ("CREATE OR REPLACE VIEW")
            )
            return f"{keyword} {target} AS\n{select};\n"
        if self.warehouse in _DROP_THEN_CREATE:
            if self.warehouse in (Warehouse.FABRIC, Warehouse.SYNAPSE):
                return f"DROP TABLE IF EXISTS {target};\nSELECT * INTO {target} FROM (\n{select}\n) AS model;\n"
            return f"DROP TABLE IF EXISTS {target};\nCREATE TABLE {target} AS\n{select};\n"
        return f"CREATE OR REPLACE TABLE {target} AS\n{select};\n"

    def incremental(self, model) -> str:
        target = self.relation(model.name)
        work = self.q(f"{model.name}__new")
        columns = ", ".join(self.q(c.name) for c in model.columns)
        keys = model.unique_key
        lines = [
            "-- An incremental model: built in full the first time, then only rows past the watermark.",
            self.create_if_missing(model.name, self.select(model)),
            "-- The rows past the watermark, kept aside while the old versions of them are removed.",
            f"DROP TABLE IF EXISTS {work};",
            f"CREATE TEMPORARY TABLE {work} AS\n{self.select(model, incremental=True)};",
        ]
        if keys:
            match = " AND ".join(f"{work}.{self.q(k)} = {target}.{self.q(k)}" for k in keys)
            lines.append(f"DELETE FROM {target} WHERE EXISTS (SELECT 1 FROM {work} WHERE {match});")
        lines += [
            f"INSERT INTO {target} ({columns})\nSELECT {columns} FROM {work};",
            f"DROP TABLE {work};",
        ]
        return "\n".join(lines) + "\n"

    def create_if_missing(self, name: str, select: str) -> str:
        target = self.relation(name)
        if self.warehouse in (Warehouse.FABRIC, Warehouse.SYNAPSE):
            return (
                f"IF OBJECT_ID('{self.schemas[name]}.{name}') IS NULL\n"
                f"    SELECT * INTO {target} FROM (\n{select}\n) AS model;"
            )
        return f"CREATE TABLE IF NOT EXISTS {target} AS\n{select};"

    def snapshot(self, snapshot) -> str:
        """dbt's snapshot (check strategy, all columns) as statements."""
        target = self.relation(snapshot.name)
        source = self.relation(_REF.search(snapshot.relation).group(1))
        names = [c.name for c in snapshot.columns]
        columns = ", ".join(self.q(n) for n in names)
        timestamp = self.target.physical_name("timestamp")
        key = " AND ".join(f"v.{self.q(k)} = {target}.{self.q(k)}" for k in snapshot.unique_key)
        changed = (
            " OR ".join(
                f"v.{self.q(n)} IS DISTINCT FROM {target}.{self.q(n)}" for n in names if n not in snapshot.unique_key
            )
            or "FALSE"
        )
        current_key = " AND ".join(f"s.{self.q(k)} = v.{self.q(k)}" for k in snapshot.unique_key)
        statements = [
            "-- Every version of each row (an SCD2 snapshot), as dbt's check strategy keeps them.",
            self.create_if_missing(
                snapshot.name,
                f"SELECT {columns}, CAST(NULL AS {timestamp}) AS dbt_valid_from, "
                f"CAST(NULL AS {timestamp}) AS dbt_valid_to\nFROM {source}\nWHERE 1 = 0",
            ),
            "-- Close the current version of every row that changed.",
            self.sql(
                f"UPDATE {target} SET dbt_valid_to = CAST(CURRENT_TIMESTAMP AS {timestamp})\n"
                f"WHERE dbt_valid_to IS NULL\n  AND EXISTS (SELECT 1 FROM {source} AS v WHERE {key} AND ({changed}))"
            )
            + ";",
            "-- Add a current version for every row that is new or changed.",
            self.sql(
                f"INSERT INTO {target} ({columns}, dbt_valid_from, dbt_valid_to)\n"
                f"SELECT {', '.join('v.' + self.q(n) for n in names)}, "
                f"CAST(CURRENT_TIMESTAMP AS {timestamp}), CAST(NULL AS {timestamp})\nFROM {source} AS v\n"
                f"WHERE NOT EXISTS (SELECT 1 FROM {target} AS s WHERE {current_key} AND s.dbt_valid_to IS NULL)"
            )
            + ";",
        ]
        return "\n".join(statements) + "\n"

    # tests --------------------------------------------------------------------------------------

    def test(self, model_name: str, test: Test) -> str:
        table = self.relation(model_name)
        column = self.q(test.column) if test.column else None
        args: dict[str, Any] = test.args
        if test.name == "unique":
            query = (
                f"SELECT {column}, COUNT(*) AS n FROM {table} "
                f"WHERE {column} IS NOT NULL GROUP BY {column} HAVING COUNT(*) > 1"
            )
        elif test.name == "not_null":
            query = f"SELECT * FROM {table} WHERE {column} IS NULL"
        elif test.name == "accepted_values":
            quote = args.get("quote", True)
            values = ", ".join(("'" + str(v).replace("'", "''") + "'") if quote else str(v) for v in args["values"])
            query = f"SELECT * FROM {table} WHERE {column} IS NOT NULL AND {column} NOT IN ({values})"
        elif test.name == "relationships":
            parent = self.relation(_REF.search(args["to"]).group(1))
            field = self.q(args["field"])
            query = (
                f"SELECT child.* FROM {table} AS child\n"
                f"WHERE child.{column} IS NOT NULL\n"
                f"  AND NOT EXISTS (SELECT 1 FROM {parent} AS parent WHERE parent.{field} = child.{column})"
            )
        elif test.name == "murakumo_range":
            bounds = []
            if args.get("min_value") is not None:
                bounds.append(f"{column} < {args['min_value']}")
            if args.get("max_value") is not None:
                bounds.append(f"{column} > {args['max_value']}")
            query = f"SELECT * FROM {table} WHERE {column} IS NOT NULL AND ({' OR '.join(bounds)})"
        elif test.name == "murakumo_unique_combination":
            names = ", ".join(self.q(c) for c in args["columns"])
            query = f"SELECT {names}, COUNT(*) AS n FROM {table} GROUP BY {names} HAVING COUNT(*) > 1"
        elif test.name == "murakumo_expression":
            query = f"SELECT * FROM {table} WHERE NOT ({args['expression']})"
        else:
            return f"-- {test.name} on {model_name}: no plain SQL form; run it with dbt.\n"
        where = f"{model_name}.{test.column}" if test.column else model_name
        severity = "" if test.severity == "error" else f" (severity: {test.severity})"
        return f"-- {test.name}: {where}{severity}\n{self.sql(query)};\n"

    # the scripts --------------------------------------------------------------------------------

    def order(self) -> list[tuple[str, Any]]:
        """Models and snapshots in an order where everything runs after what it reads."""
        nodes: dict[str, tuple[str, Any]] = {m.name: ("model", m) for m in self.plan.models}
        nodes.update({s.name: ("snapshot", s) for s in self.plan.snapshots})
        needs: dict[str, set[str]] = {}
        for name, (_kind, node) in nodes.items():
            text = node.relation + " " + " ".join(j.relation for j in getattr(node, "joins", []))
            needs[name] = {r for r in _REF.findall(text) if r in nodes}
        ordered: list[str] = []
        layers = ["staging", "intermediate", "marts", "semantic"]

        def rank(name: str) -> tuple:
            kind, node = nodes[name]
            layer = node.layer if kind == "model" else "intermediate"
            return (layers.index(layer) if layer in layers else len(layers), name)

        remaining = set(nodes)
        while remaining:
            ready = sorted((n for n in remaining if needs[n] <= set(ordered)), key=rank)
            if not ready:  # a cycle; dbt would refuse it too, so keep going in name order
                ready = sorted(remaining, key=rank)[:1]
            ordered.append(ready[0])
            remaining.discard(ready[0])
        return [nodes[n] for n in ordered]

    def render(self) -> dict[str, str]:
        header = HEADER.format(warehouse=self.warehouse.value)
        ddl = DDL(self.plan)
        landing = ddl.raw().split("\n", 1)[1]
        schemas = sorted({*self.schemas.values()})
        files = {"00_landing.sql": header + "".join(ddl.schema(s) for s in schemas) + landing}
        tests: dict[str, list[str]] = {}
        width = len(str(len(self.plan.models) + len(self.plan.snapshots)))
        for index, (kind, node) in enumerate(self.order(), start=1):
            if kind == "snapshot":
                body = self.snapshot(node)
            elif node.materialized == "incremental":
                body = self.incremental(node)
            else:
                body = self.create(
                    node.materialized if node.materialized == "view" else "table", node.name, self.select(node)
                )
            folder = self.schemas[node.name]
            files[f"{index:0{width}d}_{folder}__{node.name}.sql"] = header + body
            if kind == "model":
                for test in [*(t for c in node.columns for t in c.tests), *node.tests]:
                    tests.setdefault(node.name, []).append(self.test(node.name, test))
        for name, queries in tests.items():
            files[f"tests/{name}.sql"] = (
                header
                + "-- Each query returns the rows that fail one test: no rows means it passes.\n\n"
                + "\n".join(queries)
            )
        files["README.md"] = _readme(self.warehouse, files)
        return files


def _readme(warehouse: Warehouse, files: dict[str, str]) -> str:
    scripts = sorted(p for p in files if p.endswith(".sql") and "/" not in p)
    return (
        f"# The project as plain SQL ({warehouse.value})\n\n"
        "The same models as the dbt project in `generated/dbt`, as scripts that need nothing but the\n"
        "warehouse. Run them in order, in one session (incremental models use a temporary table):\n\n"
        + "\n".join(f"{i}. `{p}`" for i, p in enumerate(scripts, start=1))
        + "\n\nThen run the queries in `tests/`: each returns the rows that fail a test, so no rows means\n"
        "everything passed. Running the scripts again refreshes everything, as `dbt build` would: tables\n"
        "and views are re-created, incremental models add the rows past their watermark, and snapshots\n"
        "add a version for each row that changed.\n"
    )


def render(plan: Plan, dbt_files: dict[str, str]) -> dict[str, str]:
    return Plain(plan, dbt_files).render()


__all__ = ["render"]
