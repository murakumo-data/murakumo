"""Pipelines for the project's orchestrator: one per schedule, each running its dbt selector.

Every orchestrator runs the same thing: ``dbt build --selector <schedule> --target <env>`` in
``generated/dbt``, on the schedule's cron time, after checking the freshness of the sources it
reads where the orchestrator has a step for that. Only the orchestrator chosen in murakumo.yaml
is generated, under ``generated/orchestration/<orchestrator>/``.

Each pipeline finds the dbt project relative to itself, or in ``MURAKUMO_DBT_DIR`` when it is
copied elsewhere (an Airflow dags folder, say), and builds the environment in ``MURAKUMO_TARGET``
(``prod`` by default, when the project has one). Warehouse credentials come from the same
environment variables as ``profiles.yml``.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any

import yaml

from murakumo.cron import CronError, describe, quartz
from murakumo.generate.plan import Plan, snake
from murakumo.ir.model import Layer
from murakumo.manifest import Orchestrator
from murakumo.schedules import ScheduleError, dbt_models, resolve

PY_HEADER = '"""Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n\n{doc}\n"""\n'
YAML_HEADER = "# Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n"
SQL_HEADER = "-- Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n"


@dataclass
class Job:
    name: str  # the schedule
    cron: str
    when: str  # in words
    description: str
    sources: list[str]  # dbt source selections for freshness: source:group.table
    models: list[str]  # the dbt models and snapshots it builds


def _jobs(project, plan: Plan) -> list[Job]:
    timezone = project.manifest.orchestration.timezone
    # Freshness is checked only for sources that say how fresh they should be.
    groups = {
        t.entity.name.lower(): g.name for g in plan.sources for t in g.tables if g.freshness or t.entity.freshness
    }
    jobs = []
    for entry in resolve(project):
        sources = [
            f"source:{groups[e.name.lower()]}.{e.name}"
            for e in entry.entities
            if e.layer is Layer.RAW and e.name.lower() in groups
        ]
        when = describe(entry.schedule.cron, timezone)
        models = dbt_models(plan, entry.entities)
        jobs.append(
            Job(entry.schedule.name, entry.schedule.cron, when, entry.schedule.description or when, sources, models)
        )
    return jobs


def _target(project) -> str:
    environments = project.manifest.targets.environments or ["dev"]
    return "prod" if "prod" in environments else environments[-1]


def render(project, plan: Plan) -> dict[str, str]:
    """Files under generated/orchestration/<orchestrator>/, keyed by their path below it."""
    try:
        jobs = _jobs(project, plan)
    except ScheduleError:  # reported by validate (MK601)
        return {}
    orchestrator = project.manifest.generation.orchestrator
    context = {
        "project": project.manifest.project.name,
        "timezone": project.manifest.orchestration.timezone,
        "target": _target(project),
        "adapter": plan.target.adapter,
        "jobs": jobs,
    }
    renderer = {
        Orchestrator.AIRFLOW: _airflow,
        Orchestrator.GCP_COMPOSER: _airflow,
        Orchestrator.DAGSTER: _dagster,
        Orchestrator.PREFECT: _prefect,
        Orchestrator.DATABRICKS_WORKFLOWS: _databricks,
        Orchestrator.SNOWFLAKE_TASKS: _snowflake,
    }.get(orchestrator, _script)
    files = renderer(context, project.manifest)
    folder = f"orchestration/{orchestrator.value}"
    return {f"{folder}/{path}": content for path, content in files.items()}


def _py(value: Any) -> str:
    """A Python literal: strings with double quotes, as the rest of the generated code."""
    return json.dumps(value)


def _schedule_table(context: dict) -> str:
    rows = [f"| `{j.name}` | {j.when} | `{j.cron}` |" for j in context["jobs"]]
    return "| Schedule | When | Cron |\n| --- | --- | --- |\n" + "\n".join(rows)


_ENVIRONMENT = """\
Set these where the pipelines run:

- the warehouse credentials `profiles.yml` reads (see `generated/dbt/profiles.yml`);
- `MURAKUMO_TARGET` to build another environment than `{target}`;
- `MURAKUMO_DBT_DIR` if the dbt project is not at `generated/dbt`, beside `generated/orchestration/`.
"""


# Airflow (and Cloud Composer) -----------------------------------------------------------------


def _airflow(context: dict, manifest) -> dict[str, str]:
    files: dict[str, str] = {}
    for job in context["jobs"]:
        dag_id = f"{context['project']}__{job.name}"
        freshness = ""
        chain = "build"
        if job.sources:
            freshness = f"""
    freshness = BashOperator(
        task_id="source_freshness",
        bash_command=f"{{DBT}} source freshness --project-dir {{DBT_DIR}} --profiles-dir {{DBT_DIR}} "
        f"--target {{TARGET}} --select {_py(" ".join(job.sources))[1:-1]}",
    )
"""
            chain = "freshness >> build"
        files[f"dags/{snake(context['project'])}__{job.name}.py"] = (
            PY_HEADER.format(doc=f"Airflow DAG for the {job.name} schedule: {job.description}.")
            + f"""
import os
from pathlib import Path

import pendulum
from airflow import DAG
from airflow.operators.bash import BashOperator
from cosmos import DbtTaskGroup, ExecutionConfig, ProfileConfig, ProjectConfig, RenderConfig
from cosmos.constants import LoadMode

# generated/orchestration/airflow/dags/<this file> -> generated/dbt
DBT_DIR = Path(os.environ.get("MURAKUMO_DBT_DIR", Path(__file__).resolve().parents[3] / "dbt"))
TARGET = os.environ.get("MURAKUMO_TARGET", {_py(context["target"])})
DBT = os.environ.get("DBT_EXECUTABLE", "dbt")

with DAG(
    dag_id={_py(dag_id)},
    description={_py(job.description)},
    schedule={_py(job.cron)},
    start_date=pendulum.datetime(2024, 1, 1, tz={_py(context["timezone"])}),
    catchup=False,
    max_active_runs=1,
    default_args={{"retries": 2, "retry_delay": pendulum.duration(minutes=5)}},
    tags=["murakumo", {_py(context["project"])}],
):{freshness}
    build = DbtTaskGroup(
        group_id="dbt_build",
        project_config=ProjectConfig(DBT_DIR),
        profile_config=ProfileConfig(
            profile_name={_py(context["project"])},
            target_name=TARGET,
            profiles_yml_filepath=DBT_DIR / "profiles.yml",
        ),
        render_config=RenderConfig(load_method=LoadMode.DBT_LS, selector={_py(job.name)}),
        execution_config=ExecutionConfig(dbt_executable_path=DBT),
    )
    {chain}
"""
        )
    files["requirements.txt"] = f"astronomer-cosmos>=1.8\n{context['adapter']}\n"
    files["README.md"] = (
        f"# Airflow DAGs for {context['project']}\n\n"
        "One DAG per schedule. Each checks the freshness of the sources it reads, then builds its dbt\n"
        "selector with [Cosmos](https://astronomer.github.io/astronomer-cosmos/), one Airflow task per model.\n\n"
        + _schedule_table(context)
        + "\n\n## Run them\n\n"
        "1. Add `requirements.txt` to your Airflow environment (Astro: append it to the project's).\n"
        "2. Put the `dags/` files in Airflow's dags folder, and the dbt project where they can read it:\n"
        "   either copy the whole `generated/` folder so `dags/` sits beside `dbt/`, or set\n"
        "   `MURAKUMO_DBT_DIR` to the dbt project's path.\n"
        "3. The DAGs start paused: turn them on in the Airflow UI.\n\n"
        "To try one without the scheduler, run `airflow dags test <dag_id>` with\n"
        "`AIRFLOW__COSMOS__ENABLE_DATASET_ALIAS=False` set: on Airflow 2.10, `dags test` cannot save Cosmos's\n"
        "dataset aliases (scheduled runs can).\n\n" + _ENVIRONMENT.format(target=context["target"])
    )
    return files


# Dagster --------------------------------------------------------------------------------------


def _dagster(context: dict, manifest) -> dict[str, str]:
    schedules = "\n".join(
        f"""    build_schedule_from_dbt_selection(
        [{snake(context["project"])}_dbt],
        job_name={_py(job.name)},
        cron_schedule={_py(job.cron)},
        dbt_select={_py(" ".join(f"fqn:{m}" for m in job.models) or "fqn:murakumo_selects_nothing")},
        execution_timezone={_py(context["timezone"])},
        tags={{"murakumo/schedule": {_py(job.name)}}},
    ),"""
        for job in context["jobs"]
    )
    definitions = (
        PY_HEADER.format(doc="Dagster definitions: the dbt project as assets, with one schedule per Murakumo schedule.")
        + f"""
import os
from pathlib import Path

from dagster import Definitions
from dagster_dbt import DbtCliResource, DbtProject, build_schedule_from_dbt_selection, dbt_assets

DBT_DIR = Path(os.environ.get("MURAKUMO_DBT_DIR", Path(__file__).resolve().parents[2] / "dbt"))
TARGET = os.environ.get("MURAKUMO_TARGET", {_py(context["target"])})

project = DbtProject(project_dir=DBT_DIR, profiles_dir=DBT_DIR, target=TARGET)
project.prepare_if_dev()  # parses the dbt project when run with `dagster dev`
if not project.manifest_path.exists():  # elsewhere, parse it once
    project.preparer.prepare(project)


@dbt_assets(manifest=project.manifest_path, project=project)
def {snake(context["project"])}_dbt(context, dbt: DbtCliResource):
    yield from dbt.cli(["build"], context=context).stream()


schedules = [
{schedules}
]

defs = Definitions(
    assets=[{snake(context["project"])}_dbt],
    schedules=schedules,
    resources={{"dbt": DbtCliResource(project_dir=project, profiles_dir=DBT_DIR, target=TARGET)}},
)
"""
    )
    return {
        "definitions.py": definitions,
        "requirements.txt": f"dagster>=1.9\ndagster-dbt>=0.25\ndagster-webserver>=1.9\n{context['adapter']}\n",
        "README.md": (
            f"# Dagster definitions for {context['project']}\n\n"
            "Every dbt model is a Dagster asset; each Murakumo schedule is a Dagster schedule that\n"
            "materialises the models of its dbt selector.\n\n" + _schedule_table(context) + "\n\n## Run it\n\n"
            "```bash\n"
            "pip install -r requirements.txt\n"
            "dagster dev -f definitions.py   # opens http://localhost:3000\n"
            "```\n\n"
            "Schedules start stopped: turn them on under **Automation**. For production, point a Dagster\n"
            "code location (Dagster+ or your own deployment) at `definitions.py`.\n\n"
            + _ENVIRONMENT.format(target=context["target"])
        ),
    }


# Prefect --------------------------------------------------------------------------------------


def _prefect(context: dict, manifest) -> dict[str, str]:
    blocks = []
    for job in context["jobs"]:
        lines = [
            f"@flow(name={_py(context['project'] + '-' + job.name)}, description={_py(job.description)})",
            f"def {job.name}() -> None:",
        ]
        if job.sources:
            lines.append(f"    dbt({_py(['source', 'freshness', '--select', *job.sources])})")
        lines.append(f"    dbt({_py(['build', '--selector', job.name])})")
        blocks.append("\n".join(lines))
    flows = "\n\n\n".join(blocks)
    code = (
        PY_HEADER.format(doc="Prefect flows: one per Murakumo schedule, each building its dbt selector.")
        + f'''
import os
from pathlib import Path

from dbt.cli.main import dbtRunner
from prefect import flow, get_run_logger, task

DBT_DIR = Path(os.environ.get("MURAKUMO_DBT_DIR", Path(__file__).resolve().parents[2] / "dbt"))
TARGET = os.environ.get("MURAKUMO_TARGET", {_py(context["target"])})


@task(retries=2, retry_delay_seconds=300)
def dbt(arguments: list[str]) -> None:
    """Run one dbt command in the generated project; fail the task if dbt fails."""
    folder = ["--project-dir", str(DBT_DIR), "--profiles-dir", str(DBT_DIR), "--target", TARGET]
    result = dbtRunner().invoke([*arguments, *folder])
    get_run_logger().info("dbt %s: %s", " ".join(arguments), "ok" if result.success else "failed")
    if not result.success:
        raise RuntimeError(f"dbt {{' '.join(arguments)}} failed: {{result.exception or 'see the log'}}")


{flows}
'''
    )
    deployments = {
        "name": context["project"],
        "prefect-version": "3",
        "deployments": [
            {
                "name": job.name,
                "description": job.description,
                "entrypoint": f"flows.py:{job.name}",
                "schedules": [{"cron": job.cron, "timezone": context["timezone"]}],
                "work_pool": {"name": "default"},
            }
            for job in context["jobs"]
        ],
    }
    return {
        "flows.py": code,
        "prefect.yaml": YAML_HEADER + yaml.safe_dump(deployments, sort_keys=False),
        "requirements.txt": f"prefect>=3\n{context['adapter']}\n",
        "README.md": (
            f"# Prefect flows for {context['project']}\n\n"
            "One flow per schedule, each building its dbt selector, deployed on the schedule's cron time.\n\n"
            + _schedule_table(context)
            + "\n\n## Run them\n\n"
            "```bash\n"
            "pip install -r requirements.txt\n"
            f"python -c 'import flows; flows.{context['jobs'][0].name}()'   # one run, now\n"
            "prefect deploy --all                 # create the deployments from prefect.yaml\n"
            "```\n\n"
            "Change the work pool in `prefect.yaml` from `default` to yours, and start a worker for it.\n\n"
            + _ENVIRONMENT.format(target=context["target"])
        ),
    }


# Databricks Workflows ------------------------------------------------------------------------


def _databricks(context: dict, manifest) -> dict[str, str]:
    jobs: dict[str, Any] = {}
    notes = []
    for job in context["jobs"]:
        try:
            expression = quartz(job.cron)
        except CronError as exc:
            notes.append(f"- `{job.name}`: {exc}; set its schedule in the Databricks UI.")
            expression = None
        commands = ["dbt deps", f"dbt build --selector {job.name} --target {context['target']}"]
        if job.sources:
            commands.insert(1, f"dbt source freshness --select {' '.join(job.sources)} --target {context['target']}")
        definition: dict[str, Any] = {
            "name": f"{context['project']} · {job.name}",
            "description": job.description,
            "tasks": [
                {
                    "task_key": "dbt_build",
                    "dbt_task": {
                        "project_directory": "../dbt",
                        "profiles_directory": "../dbt",
                        "commands": commands,
                        "warehouse_id": "${var.warehouse_id}",
                    },
                    "environment_key": "dbt",
                }
            ],
            "environments": [{"environment_key": "dbt", "spec": {"client": "1", "dependencies": [context["adapter"]]}}],
            "max_concurrent_runs": 1,
        }
        if expression:
            definition["schedule"] = {
                "quartz_cron_expression": expression,
                "timezone_id": context["timezone"],
                "pause_status": "PAUSED",
            }
        jobs[f"{snake(context['project'])}_{job.name}"] = definition
    bundle = {
        "bundle": {"name": snake(context["project"])},
        "variables": {"warehouse_id": {"description": "The SQL warehouse dbt runs on"}},
        "sync": {"include": ["../dbt/**"]},
        "resources": {"jobs": jobs},
        "targets": {"prod": {"mode": "production"}, "dev": {"mode": "development", "default": True}},
    }
    readme = (
        f"# Databricks jobs for {context['project']}\n\n"
        "A [Databricks Asset Bundle](https://docs.databricks.com/aws/en/dev-tools/bundles/) with one job per\n"
        "schedule. Each runs a dbt task on a SQL warehouse: `dbt build --selector <schedule>`.\n\n"
        + _schedule_table(context)
        + "\n\n## Deploy\n\n"
        "```bash\n"
        "databricks bundle validate --var warehouse_id=<id>\n"
        "databricks bundle deploy -t prod --var warehouse_id=<id>\n"
        "```\n\n"
        "Schedules are deployed paused: unpause each job in the Databricks UI when you are ready.\n"
        + ("\n" + "\n".join(notes) + "\n" if notes else "")
    )
    return {
        "databricks.yml": YAML_HEADER + yaml.safe_dump(bundle, sort_keys=False, allow_unicode=True),
        "README.md": readme,
    }


# Snowflake Tasks -----------------------------------------------------------------------------


def _snowflake(context: dict, manifest) -> dict[str, str]:
    from murakumo.generate.dbt import warehouse_database

    database = warehouse_database(manifest)
    project_object = f"{database}.PUBLIC.{snake(context['project']).upper()}_DBT"
    statements = [
        SQL_HEADER,
        f"-- Snowflake tasks for {context['project']}: one per schedule, each running the dbt project",
        f"-- deployed as {project_object} (see README.md). Run as a role that owns the tasks.",
        "",
    ]
    for job in context["jobs"]:
        name = f"{database}.PUBLIC.MURAKUMO_{job.name.upper()}"
        arguments = f"build --selector {job.name} --target {context['target']}"
        statements += [
            f"-- {job.name}: {job.when}",
            f"create or replace task {name}",
            "  warehouse = TRANSFORMING",
            f"  schedule = 'USING CRON {job.cron} {context['timezone']}'",
            f"  comment = '{job.description.replace(chr(39), chr(39) * 2)}'",
            "as",
            f"  execute dbt project {project_object} args = '{arguments}';",
            f"alter task {name} resume;",
            "",
        ]
    readme = (
        f"# Snowflake tasks for {context['project']}\n\n"
        "Snowflake runs the dbt project itself ([dbt Projects on Snowflake]"
        "(https://docs.snowflake.com/en/user-guide/data-engineering/dbt-projects-on-snowflake)), and a task per\n"
        "schedule starts it on the schedule's cron time.\n\n" + _schedule_table(context) + "\n\n## Set up\n\n"
        f"1. Deploy `generated/dbt` as the dbt project object `{project_object}`, from Snowsight\n"
        "   (Projects → dbt Projects) or with the Snowflake CLI:\n"
        f"   `snow dbt deploy {snake(context['project']).upper()}_DBT --source generated/dbt`.\n"
        "2. Check `profiles.yml` for running inside Snowflake: there, the account and user come from the\n"
        "   session, and the profile's `env_var(...)` defaults must make sense without your shell.\n"
        "3. Change `TRANSFORMING` in `tasks.sql` if your warehouse has another name, then run `tasks.sql`\n"
        "   in a worksheet. The tasks start straight away (`resume`).\n"
    )
    return {"tasks.sql": "\n".join(statements), "README.md": readme}


# The rest: a script and steps ---------------------------------------------------------------


_CONSOLE_STEPS = {
    Orchestrator.AWS_GLUE: "Create a Glue Python shell job that installs `requirements.txt` and runs "
    "`run.sh <schedule>`, with a scheduled trigger per schedule (Glue triggers take the same cron fields, "
    "written `cron(0 6 * * ? *)`).",
    Orchestrator.AWS_STEP_FUNCTIONS: "Run `run.sh <schedule>` in an ECS or CodeBuild task from a state machine, and "
    "start the state machine with an EventBridge Scheduler schedule per Murakumo schedule.",
    Orchestrator.GCP_WORKFLOWS: "Run `run.sh <schedule>` as a Cloud Run job, started by a Cloud Scheduler job per "
    "schedule (Cloud Scheduler takes these cron times as they are).",
    Orchestrator.AZURE_DATA_FACTORY: "Run `run.sh <schedule>` in an Azure Container Apps job or a Batch task from a "
    "pipeline, with a schedule trigger per Murakumo schedule.",
}


def _script(context: dict, manifest) -> dict[str, str]:
    orchestrator = manifest.generation.orchestrator
    cases = []
    for job in context["jobs"]:
        lines = [f"  {job.name})  # {job.when}"]
        if job.sources:
            lines.append(f'    dbt source freshness --select {" ".join(job.sources)} "${{common[@]}}"')
        lines.append(f'    dbt build --selector {job.name} "${{common[@]}}"')
        lines.append("    ;;")
        cases.append("\n".join(lines))
    names = " | ".join(j.name for j in context["jobs"])
    script = f"""#!/usr/bin/env bash
# Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.
# Run one schedule of {context["project"]}: ./run.sh <{names}>
set -euo pipefail
here="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
dbt_dir="${{MURAKUMO_DBT_DIR:-$here/../../dbt}}"
common=(--project-dir "$dbt_dir" --profiles-dir "$dbt_dir" --target "${{MURAKUMO_TARGET:-{context["target"]}}}")
case "${{1:-}}" in
{chr(10).join(cases)}
  *)
    echo "usage: $0 <{names}>" >&2
    exit 2
    ;;
esac
"""
    readme = (
        f"# Running {context['project']} on {orchestrator.value}\n\n"
        f"Murakumo does not generate {orchestrator.value} definitions yet. `run.sh` runs one schedule;\n"
        "start it from the service on each schedule's cron time.\n\n"
        + _schedule_table(context)
        + "\n\n## Set up\n\n"
        + _CONSOLE_STEPS.get(orchestrator, "Start `run.sh <schedule>` on each schedule's cron time.")
        + "\n\n"
        + _ENVIRONMENT.format(target=context["target"])
    )
    return {"run.sh": script, "requirements.txt": f"{context['adapter']}\n", "README.md": readme}


