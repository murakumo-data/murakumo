"""Ingestion by a tool that is not Murakumo's own scripts: dlt, Airbyte or Fivetran
(``stack.extract``).

Whichever tool fetches the data, the rest of the platform is the same: staging reads each raw
table's columns as the model names them, with ``_ingested_at`` and ``_batch_id`` beside them.

- **dlt** loads straight into the raw tables. ``generated/ingestion/dlt/pipeline.py`` has a
  function per source built from its connection (databases, REST APIs, files), keeps the sources'
  column names, and adds the two columns itself.
- **Airbyte** and **Fivetran** are set up in their own product. Murakumo writes what to set up
  (``connections.json``: each table, how it syncs, its key and cursor) and ``views.sql``: a view
  per raw table over what the tool lands, giving the model's column names and the two columns
  from the tool's own (``_airbyte_extracted_at``, ``_fivetran_synced``).

Sources these tools are not given (SFTP, protobuf and Kafka with dlt) keep Murakumo's scripts.
"""

from __future__ import annotations

import json
from typing import Any

from murakumo import loading
from murakumo.generate.plan import Plan, quote_identifier, snake
from murakumo.manifest import SourceDeclaration, Warehouse

MANAGED = ("dlt", "airbyte", "fivetran")
DLT_KINDS = ("database", "rest", "files")
PY_HEADER = '"""Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n\n{doc}\n"""\n'
SQL_HEADER = "-- Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n"

# dlt's name for each warehouse, and the extra that installs it.
DLT_DESTINATIONS = {
    Warehouse.DUCKDB: "duckdb",
    Warehouse.SNOWFLAKE: "snowflake",
    Warehouse.DATABRICKS: "databricks",
    Warehouse.BIGQUERY: "bigquery",
    Warehouse.POSTGRES: "postgres",
    Warehouse.REDSHIFT: "redshift",
    Warehouse.SYNAPSE: "synapse",
    Warehouse.FABRIC: "mssql",
}


def uses_scripts(project, declaration: SourceDeclaration) -> bool:
    """Whether a source is still fetched by Murakumo's own extract script."""
    extract = project.manifest.stack.extract
    if extract not in MANAGED:
        return extract != "none"
    return extract == "dlt" and declaration.connection.kind not in DLT_KINDS  # type: ignore[union-attr]


def _schemas(plan: Plan) -> dict[str, str]:
    """Raw table -> its schema."""
    return {t.entity.name: g.schema for g in plan.sources for t in g.tables}


def _disposition(entity) -> tuple[str, list[str]]:
    if entity is None:
        return "append", []
    mode = loading.mode(entity)
    if mode == "full":
        return "replace", []
    if mode == "incremental":
        return "merge", loading.keys(entity)
    return "append", []


# dlt ------------------------------------------------------------------------------------------


def _py(value: Any) -> str:
    return json.dumps(value)


def _env(name: str | None) -> str:
    return f"os.environ[{_py(name)}]" if name else "None"


def _dlt_hints(project, table: str) -> str:
    disposition, keys = _disposition(project.model.entity(table))
    hints = f"table_name={_py(table)}, write_disposition={_py(disposition)}"
    return hints + (f", primary_key={_py(keys)}" if keys else "")


def _dlt_database(project, declaration: SourceDeclaration) -> tuple[list[str], list[str]]:
    lines, notes = ["    from dlt.sources.sql_database import sql_table", ""], []
    connection = declaration.connection
    for query in connection.tables:  # type: ignore[union-attr]
        if " " in query.source.strip():
            notes.append(
                f"{query.table} is fetched by a query, which dlt's sql_table does not take: fetch it as a table"
            )
            continue
        schema, _, name = query.source.rpartition(".")
        entity = project.model.entity(query.table)
        cursor = query.incremental_column or (entity.watermark if entity is not None else None)
        arguments = [f"credentials={_env(connection.url_env)}", f"table={_py(name)}"]  # type: ignore[union-attr]
        if schema:
            arguments.append(f"schema={_py(schema)}")
        if cursor:
            arguments.append(f"incremental=dlt.sources.incremental({_py(cursor)})")
        lines += [
            f"    resources.append(sql_table({', '.join(arguments)}).apply_hints({_dlt_hints(project, query.table)}))"
        ]
    return lines, notes


def _dlt_files(project, declaration: SourceDeclaration) -> tuple[list[str], list[str]]:
    # CSV through pandas: dlt's DuckDB reader does not run on DuckDB 2.
    readers = {
        "csv": "read_csv()",
        "tsv": "read_csv(sep='\\t')",
        "parquet": "read_parquet()",
        "jsonl": "read_jsonl()",
        "json": "read_jsonl()",
    }
    lines = ["    from dlt.sources.filesystem import filesystem, read_csv, read_jsonl, read_parquet", ""]
    notes: list[str] = []
    location = declaration.connection.location  # type: ignore[union-attr]
    where = _py(location) if "://" in location else f"(PROJECT_DIR / {_py(location)}).as_uri()"
    for found in declaration.connection.files:  # type: ignore[union-attr]
        fmt = found.format or found.pattern.rsplit(".", 1)[-1].lower()
        if fmt not in readers:
            notes.append(f"{found.table}: dlt has no reader for {fmt} files here; it keeps Murakumo's script")
            continue
        reader = readers[fmt]
        lines += [f"    files = filesystem(bucket_url={where}, file_glob={_py(found.pattern)})"]
        if _disposition(project.model.entity(found.table))[0] != "replace":
            # Each file is read once: dlt remembers the newest one it has loaded. (A table loaded in
            # full reads every file each time, and is replaced.)
            lines += ['    files.apply_hints(incremental=dlt.sources.incremental("modification_date"))']
        lines += [
            f"    resources.append((files | {reader}).with_name({_py(found.table)})"
            f".apply_hints({_dlt_hints(project, found.table)}))",
        ]
    return lines, notes


def _dlt_rest(project, declaration: SourceDeclaration) -> tuple[list[str], list[str]]:
    connection = declaration.connection
    auth, paging = connection.auth, connection.paging  # type: ignore[union-attr]
    client: dict[str, Any] = {"base_url": connection.base_url + "/"}  # type: ignore[union-attr]
    if connection.headers:  # type: ignore[union-attr]
        client["headers"] = dict(connection.headers)  # type: ignore[union-attr]
    secrets: dict[str, str] = {}  # placeholder -> the Python that reads the secret

    def secret(name: str | None) -> str:
        placeholder = f"@@{name}@@"
        secrets[placeholder] = _env(name)
        return placeholder

    if auth.type == "bearer":
        client["auth"] = {"type": "bearer", "token": secret(auth.env)}
    elif auth.type == "api_key":
        client["auth"] = {"type": "api_key", "name": auth.name, "api_key": secret(auth.env), "location": auth.location}
    elif auth.type == "basic":
        client["auth"] = {
            "type": "http_basic",
            "username": secret(auth.user_env),
            "password": secret(auth.password_env),
        }
    elif auth.type == "oauth2":
        client["auth"] = {
            "type": "oauth2_client_credentials",
            "access_token_url": auth.token_url,
            "client_id": secret(auth.client_id_env),
            "client_secret": secret(auth.client_secret_env),
            **({"access_token_request_data": {"scope": auth.scope}} if auth.scope else {}),
        }
    if paging.type == "page":
        client["paginator"] = {
            "type": "page_number",
            "page_param": paging.param or "page",
            "base_page": paging.start,
            "total_path": None,
            **({"maximum_page": paging.max_pages} if paging.max_pages else {}),
        }
    elif paging.type == "offset":
        client["paginator"] = {
            "type": "offset",
            "limit": paging.size,
            "offset_param": paging.param or "offset",
            "limit_param": paging.size_param or "limit",
            "total_path": None,
        }
    elif paging.type == "cursor":
        client["paginator"] = {
            "type": "cursor",
            "cursor_path": paging.cursor_path,
            "cursor_param": paging.param or "cursor",
        }
    elif paging.type == "link":
        client["paginator"] = {"type": "header_link"}
    elif paging.type == "next_url":
        path = paging.next_path or "next"
        client["paginator"] = {
            "type": "json_link",
            "next_url_path": f"'{path}'" if "." in path or "@" in path else path,
        }
    else:
        client["paginator"] = {"type": "single_page"}
    resources = []
    for endpoint in connection.endpoints:  # type: ignore[union-attr]
        entity = project.model.entity(endpoint.table)
        disposition, keys = _disposition(entity)
        params: dict[str, Any] = dict(endpoint.params)
        if paging.type in ("page", "offset") and paging.size_param and paging.type == "page":
            params[paging.size_param] = paging.size
        # A parameter written around the watermark (modifiedon ge {since}) is fetched in full here.
        if endpoint.since_param and not endpoint.since_format and entity is not None and entity.watermark:
            params[endpoint.since_param] = {
                "type": "incremental",
                "cursor_path": entity.watermark,
                "initial_value": "1970-01-01T00:00:00Z",
            }
        spec: dict[str, Any] = {"path": endpoint.path.lstrip("/"), "method": endpoint.method}
        if params:
            spec["params"] = params
        if endpoint.body is not None:
            spec["json"] = endpoint.body
        if endpoint.records:
            spec["data_selector"] = endpoint.records
        resource: dict[str, Any] = {"name": endpoint.table, "endpoint": spec, "write_disposition": disposition}
        if keys:
            resource["primary_key"] = keys
        resources.append(resource)
    config = json.dumps({"client": client, "resources": resources}, indent=4)
    for placeholder, code in secrets.items():
        config = config.replace(_py(placeholder), code)
    config = config.replace(": null", ": None").replace(": true", ": True").replace(": false", ": False")
    indented = "\n".join("    " + line for line in config.splitlines())
    lines = [
        "    from dlt.sources.rest_api import rest_api_source",
        "",
        f"    config = {indented.strip()}",
        "    resources.extend(rest_api_source(config).resources.values())",
    ]
    return lines, []


def _dlt(project, plan: Plan, sources: list[SourceDeclaration]) -> dict[str, str]:
    name = snake(project.manifest.project.name)
    warehouse = plan.target.warehouse
    destination = DLT_DESTINATIONS[warehouse]
    schemas = _schemas(plan)
    functions, registry, notes, kinds = [], [], [], set()
    for declaration in sources:
        kind = declaration.connection.kind  # type: ignore[union-attr]
        if kind not in DLT_KINDS:
            notes.append(f"{declaration.name} ({kind}) is fetched by Murakumo's own script, not dlt")
            continue
        builder = {"database": _dlt_database, "files": _dlt_files, "rest": _dlt_rest}[kind]
        body, found = builder(project, declaration)
        notes += found
        kinds.add(kind)
        tables = declaration.tables()
        dataset = next((schemas[t] for t in tables if t in schemas), f"raw_{snake(declaration.name)}")
        function = snake(declaration.name)
        functions.append(
            f"def {function}():\n"
            f'    """{declaration.name}: {", ".join(tables)}, into {dataset}."""\n'
            "    resources = []\n" + "\n".join(body) + f"\n    return {_py(dataset)}, resources\n"
        )
        registry.append(f"    {_py(declaration.name)}: {function},")
    if warehouse is Warehouse.DUCKDB:
        configured = project.manifest.targets.warehouse.database or ""
        path = configured if configured.endswith((".duckdb", ".db")) else f"{project.manifest.project.name}.duckdb"
        where = (
            "    # The same DuckDB file the builds use.\n"
            f'    path = os.environ.get("MURAKUMO_DUCKDB_PATH") or str(PROJECT_DIR / {_py(path)})\n'
            "    return dlt.destinations.duckdb(path)\n"
        )
    else:
        where = (
            "    # Its credentials come from dlt's own settings: .dlt/secrets.toml, or variables such as\n"
            f"    # DESTINATION__{destination.upper()}__CREDENTIALS (see the README).\n"
            f"    return {_py(destination)}\n"
        )
    doc = (
        f"Fetch {project.manifest.project.name}'s sources with dlt, straight into the raw tables.\n\n"
        "    python pipeline.py              # every source\n"
        "    python pipeline.py <source>     # one of them"
    )
    code = (
        PY_HEADER.format(doc=doc)
        + f'''
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Keep the sources' column names as they are (VendorID, not vendor_id): staging reads them by name.
os.environ.setdefault("SCHEMA__NAMING", "direct")

import dlt  # noqa: E402

PROJECT_DIR = Path(os.environ.get("MURAKUMO_PROJECT_DIR", Path(__file__).resolve().parents[3]))
NOW = datetime.now(timezone.utc)
BATCH = NOW.strftime("dlt_%Y%m%d_%H%M%S")


def stamp(row):
    """The two columns every raw table has: when the row arrived, and in which run."""
    row["_ingested_at"] = NOW
    row["_batch_id"] = BATCH
    return row


def rows(record):
    """One row per record. A record that is columns of values (lists of one length, as some APIs
    answer: {{"time": [...], "temperature": [...]}}) is one row per position."""
    values = list(record.values()) if isinstance(record, dict) else []
    if values and all(isinstance(value, list) for value in values) and len({{len(value) for value in values}}) == 1:
        for parts in zip(*values):
            yield stamp(dict(zip(record, parts)))
    else:
        yield stamp(record)


def destination():
{where}

{chr(10).join(functions)}

SOURCES = {{
{chr(10).join(registry)}
}}


def adopt(pipeline, tables):
    """A raw table that was loaded before dlt took over has no _dlt_load_id or _dlt_id, and dlt
    cannot add them to a table that already has rows. Add them here, empty; where the table is not
    there yet, or has them, nothing happens."""
    try:
        with pipeline.sql_client() as client:
            for table in tables:
                name = client.make_qualified_table_name(table)
                for column in ("_dlt_load_id", "_dlt_id"):
                    for kind in ("varchar", "string"):
                        try:
                            client.execute_sql(f"alter table {{name}} add column {{column}} {{kind}}")
                            break
                        except Exception:  # noqa: BLE001 - no such table, or it has the column
                            continue
    except Exception:  # noqa: BLE001 - nothing loaded yet: dlt creates everything
        pass


def run(names):
    for name in names:
        dataset, resources = SOURCES[name]()
        pipeline = dlt.pipeline(pipeline_name=f"{name}_{{name}}", destination=destination(), dataset_name=dataset)
        adopt(pipeline, [resource.name for resource in resources])
        print(pipeline.run([resource.add_yield_map(rows) for resource in resources]))


if __name__ == "__main__":
    unknown = [name for name in sys.argv[1:] if name not in SOURCES]
    if unknown:
        sys.exit(f"no source {{', '.join(unknown)}}: {{', '.join(SOURCES)}}")
    run(sys.argv[1:] or list(SOURCES))
'''
    )
    extras = sorted({destination} | ({"sql_database"} if "database" in kinds else set()))
    extras += ["filesystem"] if "files" in kinds else []
    csv = any(
        (f.format or f.pattern.rsplit(".", 1)[-1].lower()) in ("csv", "tsv")
        for d in sources
        if d.connection.kind == "files"
        for f in d.connection.files
    )
    readme = (
        f"# Fetching {project.manifest.project.name}'s sources with dlt\n\n"
        "[dlt](https://dlthub.com) fetches each source and loads it into its raw tables, creating them and\n"
        "adding new columns as the source grows. `pipeline.py` has one function per source.\n\n"
        "```bash\n"
        "pip install -r generated/ingestion/dlt/requirements.txt\n"
        "python generated/ingestion/dlt/pipeline.py            # every source\n"
        f"python generated/ingestion/dlt/pipeline.py {sources[0].name}   # one\n"
        "```\n\n"
        'With Murakumo installed with its dlt extra (`pip install "murakumo[dlt]"`), `murakumo ingest` runs it.\n\n'
        "- The sources' secrets are read from the same environment variables as before.\n"
        + (
            "- The warehouse is the project's DuckDB file.\n"
            if warehouse is Warehouse.DUCKDB
            else f"- Give dlt the warehouse's credentials: `DESTINATION__{destination.upper()}__CREDENTIALS`, or\n"
            "  `.dlt/secrets.toml` beside where you run it ([dlt's destinations](https://dlthub.com/docs/dlt-ecosystem/destinations/)).\n"
        )
        + "- Column names are kept as the source has them, and every row gets `_ingested_at` and `_batch_id`,\n"
        "  so staging reads the raw tables as it does with any other way of loading them.\n"
        "- A table loaded `full` is replaced, `append` is added to, and `incremental` is merged by its key.\n"
        "- The orchestrator runs this before each build, for the sources its schedule reads.\n"
        + ("\n" + "\n".join(f"- {note}" for note in notes) + "\n" if notes else "")
    )
    return {
        "ingestion/dlt/pipeline.py": code,
        "ingestion/dlt/requirements.txt": f"dlt[{','.join(extras)}]>=1.4\n" + ("pandas>=2.0\n" if csv else ""),
        "ingestion/dlt/README.md": readme,
    }


# Airbyte and Fivetran -------------------------------------------------------------------------

TOOLS = {
    "airbyte": {
        "title": "Airbyte",
        "ingested": "_airbyte_extracted_at",
        "deleted": None,
        "rename": lambda name: name,  # Airbyte keeps the source's column names
        "docs": "https://docs.airbyte.com",
    },
    "fivetran": {
        "title": "Fivetran",
        "ingested": "_fivetran_synced",
        "deleted": "_fivetran_deleted",
        "rename": snake,  # Fivetran writes names in lower snake_case
        "docs": "https://fivetran.com/docs",
    },
}


def landed_schema(schema: str, tool: str) -> str:
    """Where the tool lands a source: the raw schema's name with the tool's after it."""
    return f"{schema}_{tool}"


def views_sql(project, plan: Plan, tool: str) -> str:
    """A view per raw table over what the tool landed: the model's column names, and the two
    columns every raw table has."""
    settings = TOOLS[tool]
    dialect = plan.target.dialect
    tsql = plan.target.warehouse in (Warehouse.FABRIC, Warehouse.SYNAPSE)
    string = plan.target.physical_name("string")
    q = lambda name: quote_identifier(name, dialect)  # noqa: E731
    filled = {t for d in project.manifest.sources if d.connection is not None for t in d.tables()}
    out = [
        SQL_HEADER,
        f"-- {settings['title']} lands each source in a schema of its own (<raw schema>_{tool}). These views give",
        "-- the raw tables the model describes: its column names, with _ingested_at and _batch_id.",
        "-- Run this once, and again after the model's raw tables change.",
        "",
    ]
    for group in plan.sources:
        tables = [t for t in group.tables if t.entity.name in filled]
        if not tables:
            continue
        if tsql:
            out.append(
                f"IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = '{group.schema}') "
                f"EXEC('CREATE SCHEMA {group.schema}');"
            )
        else:
            keyword = "DATASET" if plan.target.warehouse is Warehouse.BIGQUERY else "SCHEMA"
            out.append(f"CREATE {keyword} IF NOT EXISTS {q(group.schema)};")
        for table in tables:
            entity = table.entity
            columns = [f"    {q(settings['rename'](a.name))} AS {q(a.name)}" for a in entity.attributes]  # type: ignore[operator]
            columns += [
                f"    {settings['ingested']} AS _ingested_at",
                f"    CAST({settings['ingested']} AS {string}) AS _batch_id",
            ]
            keyword = "CREATE OR ALTER VIEW" if tsql else "CREATE OR REPLACE VIEW"
            source = f"{q(landed_schema(group.schema, tool))}.{q(settings['rename'](entity.name))}"  # type: ignore[operator]
            statement = f"{keyword} {q(group.schema)}.{q(entity.name)} AS\nSELECT\n" + ",\n".join(columns)
            statement += f"\nFROM {source}"
            if settings["deleted"]:
                # Rows the source deleted stay in what the tool landed, marked: leave them out.
                statement += (
                    f"\nWHERE COALESCE({settings['deleted']}, {'0' if tsql else 'FALSE'}) = {'0' if tsql else 'FALSE'}"
                )
            out += ["", statement + ";"]
        out.append("")
    return "\n".join(out)


def connections(project, plan: Plan, tool: str, sources: list[SourceDeclaration]) -> list[dict[str, Any]]:
    """What to set up in the tool: one connection per source, and how each table syncs."""
    schemas = _schemas(plan)
    out = []
    for declaration in sources:
        connection = declaration.connection
        tables = []
        for table in declaration.tables():
            entity = project.model.entity(table)
            mode = "append" if entity is None else loading.mode(entity)
            cdc = entity is not None and entity.load.value == "cdc"
            sync = {
                "full": "full refresh, overwrite",
                "append": "incremental, append",
                "incremental": "incremental, append and deduplicate",
            }[mode]
            tables.append(
                {
                    "table": table,
                    "sync": "change data capture (the database's log)" if cdc else sync,
                    "primary_key": loading.keys(entity) if entity is not None else [],
                    "cursor": entity.watermark if entity is not None else None,
                    "columns": [a.name for a in entity.attributes] if entity is not None else [],
                }
            )
        schema = next((schemas[t] for t in declaration.tables() if t in schemas), f"raw_{snake(declaration.name)}")
        detail = connection.model_dump(exclude_none=True)  # type: ignore[union-attr]
        out.append(
            {
                "source": declaration.name,
                "kind": detail.pop("kind"),
                "settings": {
                    k: v for k, v in detail.items() if k not in ("tables", "endpoints", "files", "topics", "messages")
                },
                "destination_schema": landed_schema(schema, tool),
                "schedule": declaration.ingestion.schedule,
                "tables": tables,
            }
        )
    return out


def _tool(project, plan: Plan, tool: str, sources: list[SourceDeclaration]) -> dict[str, str]:
    settings = TOOLS[tool]
    title = settings["title"]
    found = connections(project, plan, tool, sources)
    rows = "\n".join(
        f"| `{c['source']}` | {c['kind']} | `{c['destination_schema']}` | {len(c['tables'])} |" for c in found
    )
    readme = (
        f"# Fetching {project.manifest.project.name}'s sources with {title}\n\n"
        f"{title} is set up in its own product; Murakumo writes what to set up and makes what it lands look\n"
        "like the raw tables the model describes.\n\n"
        "| Source | Kind | Lands in | Tables |\n| --- | --- | --- | --- |\n" + rows + "\n\n## Set it up\n\n"
        f"1. In {title}, create a connection per source in `connections.json`: the source's settings are\n"
        "   there (secrets are named by their environment variable; enter the values in the tool), with\n"
        "   each table's sync mode, key and cursor column.\n"
        "2. Point each connection at the destination schema `connections.json` names for it\n"
        f"   (`<raw schema>_{tool}`), in the project's warehouse.\n"
        "3. Run a first sync, then run `views.sql` in the warehouse. It creates a view per raw table with the\n"
        "   model's column names, `_ingested_at` and `_batch_id`"
        + (", without the rows the source deleted" if settings["deleted"] else "")
        + ".\n"
        "4. Build as usual: `murakumo build` (or the orchestrator) reads the views.\n\n"
        f"Murakumo does not create the raw tables or load them with `stack.extract: {tool}`: the tool does.\n"
        "Run `views.sql` again after a raw table gains or loses a column in the model.\n\n"
        f"{title}'s documentation: {settings['docs']}\n"
    )
    return {
        f"ingestion/{tool}/connections.json": json.dumps(found, indent=2) + "\n",
        f"ingestion/{tool}/views.sql": views_sql(project, plan, tool),
        f"ingestion/{tool}/README.md": readme,
    }


def render(project, plan: Plan, sources: list[SourceDeclaration]) -> dict[str, str]:
    extract = project.manifest.stack.extract
    if extract == "dlt":
        return _dlt(project, plan, sources)
    if extract in TOOLS:
        return _tool(project, plan, extract, sources)
    return {}


