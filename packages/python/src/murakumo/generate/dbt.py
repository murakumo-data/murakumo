"""Render a plan as a complete dbt project: a mapping of relative path to file content."""

from __future__ import annotations

from importlib import resources
from typing import Any

import yaml
from jinja2 import Environment, PackageLoader, StrictUndefined

from murakumo.generate.plan import DbtModel, Plan, Test, freshness_config, quote_identifier, snake
from murakumo.manifest import Warehouse

HEADER = "-- Generated by Murakumo from {origin}. Do not edit: change the model, then run `murakumo generate`."
YAML_HEADER = "# Generated by Murakumo. Do not edit: change the model, then run `murakumo generate`.\n"

_env = Environment(
    loader=PackageLoader("murakumo.generate", "templates/dbt"),
    undefined=StrictUndefined,
    keep_trailing_newline=True,
    trim_blocks=False,
    autoescape=False,  # noqa: S701 - this renders SQL, not HTML
)


class _Dumper(yaml.SafeDumper):
    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        return super().increase_indent(flow, False)


def _yaml(data: Any) -> str:
    return YAML_HEADER + yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)


def render(plan: Plan) -> dict[str, str]:
    files: dict[str, str] = {}
    project = plan.project
    files["dbt_project.yml"] = _yaml(_dbt_project(plan))
    files["profiles.yml"] = _yaml(profiles(plan))
    files["README.md"] = _readme(plan)

    for group in plan.sources:
        files[f"models/staging/{group.name}/_{group.name}__sources.yml"] = _yaml(_sources(group))

    by_folder: dict[str, list[DbtModel]] = {}
    for model in plan.models:
        by_folder.setdefault(model.folder, []).append(model)
        origin = project.origins.get(model.entity.id)
        where = origin.relative_to(project.root) if origin else "the model"
        header = HEADER.format(origin=where)
        template = "staging.sql.j2" if model.layer == "staging" else "model.sql.j2"
        files[f"models/{model.folder}/{model.name}.sql"] = _env.get_template(template).render(
            model=model, header=header, quote=lambda n: quote_identifier(n, plan.target.dialect), config=_config(model)
        )
    for folder, models in sorted(by_folder.items()):
        leaf = folder.rsplit("/", 1)[-1]
        files[f"models/{folder}/_{leaf}__models.yml"] = _yaml(
            {"version": 2, "models": [_model_yaml(m, plan) for m in models]}
        )

    groups = _groups(plan)
    if groups:
        files["models/_groups.yml"] = _yaml({"version": 2, "groups": groups})

    if plan.snapshots:
        files["snapshots/_snapshots.yml"] = _yaml(
            {
                "snapshots": [
                    {
                        "name": s.name,
                        "description": s.description,
                        "relation": s.relation,
                        "config": {
                            "schema": "snapshots",
                            "unique_key": s.unique_key[0] if len(s.unique_key) == 1 else s.unique_key,
                            "strategy": "check",
                            "check_cols": "all",
                        },
                    }
                    for s in plan.snapshots
                ]
            }
        )

    macros = resources.files("murakumo.generate").joinpath("templates/dbt/macros")
    for macro in sorted(macros.iterdir(), key=lambda p: p.name):
        if macro.name.endswith(".sql"):
            files[f"macros/murakumo/{macro.name}"] = macro.read_text(encoding="utf-8")
    return dict(sorted(files.items()))


def _config(model: DbtModel) -> str:
    """The config() arguments for a model's SQL file."""
    if model.layer == "staging":
        return ""
    parts = [f"materialized={model.materialized!r}"]
    if model.materialized == "incremental":
        key = model.unique_key[0] if len(model.unique_key) == 1 else model.unique_key
        if key:
            parts.append(f"unique_key={key!r}")
        parts.append("on_schema_change='append_new_columns'")
        parts.append("incremental_strategy='delete+insert'" if model.unique_key else "incremental_strategy='append'")
    for key, value in model.config.items():
        parts.append(f"{key}={value!r}")
    return ", ".join(parts)


def _test(test: Test, plan: Plan, model: DbtModel) -> Any:
    args = dict(test.args)
    if test.name == "accepted_values":
        # Numbers are compared as numbers, so 1 matches 1 on every warehouse.
        attribute = next((a for a in model.entity.attributes if test.column in (a.name, snake(a.name))), None)
        if attribute is not None and attribute.logical_type.family in ("integer", "number"):
            try:
                args = {"values": [_number(v) for v in args["values"]], "quote": False}
            except ValueError:
                pass
    body: dict[str, Any] = {}
    if args:
        body["arguments"] = args
    if test.severity != "error":
        body["config"] = {"severity": test.severity}
    return {test.name: body} if body else test.name


def _number(value: str) -> int | float:
    number = float(value)
    return int(number) if number.is_integer() else number


def selectors(project, plan: Plan) -> str:
    """One dbt selector per schedule, so orchestrators run ``dbt build --selector <schedule>``."""
    from murakumo.schedules import ScheduleError, dbt_selectors

    try:
        return _yaml(dbt_selectors(project, plan))
    except ScheduleError:  # reported by validate (MK601); generate what can be generated
        return _yaml({"selectors": []})


def _groups(plan: Plan) -> list[dict]:
    """One dbt group per domain that has models, owned by the domain's owner."""
    used = {(m.entity.domain or "").lower() for m in plan.models}
    groups = []
    for domain in plan.project.manifest.project.domains:
        if domain.name.lower() not in used:
            continue
        group: dict[str, Any] = {"name": domain.name, "owner": {"name": domain.owner or f"{domain.name} domain"}}
        if domain.description:
            group["description"] = domain.description
        groups.append(group)
    return groups


def _model_yaml(model: DbtModel, plan: Plan) -> dict:
    data: dict[str, Any] = {"name": model.name}
    if model.description:
        data["description"] = model.description
    config: dict[str, Any] = {}
    domain = plan.project.manifest.domain(model.entity.domain) if model.entity.domain else None
    if domain is not None:
        config["group"] = domain.name
        config["meta"] = {"domain": domain.name}
    if model.contract:
        config["contract"] = {"enforced": True}
    if config:
        data["config"] = config
    columns = []
    for column in model.columns:
        entry: dict[str, Any] = {"name": column.name}
        if column.description:
            entry["description"] = column.description
        if model.contract:
            entry["data_type"] = column.data_type
        if column.meta:
            entry["meta"] = column.meta
        if column.tests:
            entry["data_tests"] = [_test(t, plan, model) for t in column.tests]
        if column.name != column.name.lower() or not column.name.replace("_", "").isalnum():
            entry["quote"] = True
        columns.append(entry)
    data["columns"] = columns
    if model.tests:
        data["data_tests"] = [_test(t, plan, model) for t in model.tests]
    return data


def _sources(group) -> dict:
    source: dict[str, Any] = {
        "name": group.name,
        "schema": f"{{{{ env_var('MURAKUMO_SCHEMA_PREFIX', '') }}}}{group.schema}",
    }
    if group.description:
        source["description"] = group.description
    source["loaded_at_field"] = "_ingested_at"
    if group.freshness:
        source["freshness"] = group.freshness
    tables = []
    for table in group.tables:
        entry: dict[str, Any] = {"name": table.entity.name}
        if table.entity.description:
            entry["description"] = table.entity.description
        if table.entity.freshness:
            entry["freshness"] = freshness_config(table.entity.freshness)
        if table.entity.name != table.entity.name.lower():
            entry["quoting"] = {"identifier": True}
        columns = []
        for attribute in table.entity.attributes:
            column: dict[str, Any] = {"name": attribute.name}
            if attribute.description:
                column["description"] = attribute.description
            if attribute.name != attribute.name.lower():
                column["quote"] = True
            columns.append(column)
        entry["columns"] = columns
        tables.append(entry)
    source["tables"] = tables
    return {"version": 2, "sources": [source]}


def _dbt_project(plan: Plan) -> dict:
    name = plan.project.manifest.project.name
    layers = {
        "staging": {"+materialized": "view", "+schema": "staging"},
        "intermediate": {"+materialized": "view", "+schema": "intermediate"},
        "marts": {"+materialized": "table", "+schema": "marts"},
        "semantic": {"+materialized": "view", "+schema": "semantic"},
    }
    return {
        "name": name,
        "version": "1.0.0",
        "config-version": 2,
        "profile": name,
        "model-paths": ["models"],
        "snapshot-paths": ["snapshots"],
        "macro-paths": ["macros"],
        "test-paths": ["tests"],
        "clean-targets": ["target", "dbt_packages"],
        "require-dbt-version": ">=1.10.0",
        **(
            {
                "on-run-start": ["{{ murakumo_audit_setup() }}"],
                "on-run-end": ["{{ murakumo_audit(results) }}"],
            }
            if plan.project.manifest.quality.run_log
            else {}
        ),
        "models": {name: layers},
    }


def profiles(plan: Plan) -> dict:
    """profiles.yml: one output per environment, credentials read from environment variables."""
    manifest = plan.project.manifest
    name = manifest.project.name
    warehouse = plan.target.warehouse
    configured = manifest.targets.warehouse.database
    is_file = _is_file(configured)
    database = warehouse_database(manifest)
    outputs = {}
    for environment in manifest.targets.environments:
        upper = environment.upper()
        schema = f"{{{{ env_var('MURAKUMO_SCHEMA', '{environment}') }}}}"
        if warehouse is Warehouse.DUCKDB:
            path = configured if is_file else f"{name}.duckdb"
            outputs[environment] = {
                "type": "duckdb",
                "path": f"{{{{ env_var('MURAKUMO_DUCKDB_PATH', '{path}') }}}}",
                "schema": schema,
                "threads": 4,
            }
        elif warehouse is Warehouse.SNOWFLAKE:
            outputs[environment] = {
                "type": "snowflake",
                "account": "{{ env_var('SNOWFLAKE_ACCOUNT') }}",
                "user": "{{ env_var('SNOWFLAKE_USER') }}",
                "authenticator": "{{ env_var('SNOWFLAKE_AUTHENTICATOR', 'snowflake_jwt') }}",
                "private_key_path": "{{ env_var('SNOWFLAKE_PRIVATE_KEY_PATH', '') }}",
                "role": f"{{{{ env_var('SNOWFLAKE_ROLE_{upper}', 'TRANSFORMER') }}}}",
                "warehouse": "{{ env_var('SNOWFLAKE_WAREHOUSE', 'TRANSFORMING') }}",
                "database": f"{{{{ env_var('SNOWFLAKE_DATABASE', '{database}') }}}}",
                "schema": schema,
                "threads": 8,
            }
        elif warehouse is Warehouse.DATABRICKS:
            outputs[environment] = {
                "type": "databricks",
                "host": "{{ env_var('DATABRICKS_HOST') }}",
                "http_path": "{{ env_var('DATABRICKS_HTTP_PATH') }}",
                "token": "{{ env_var('DATABRICKS_TOKEN') }}",
                "catalog": database.lower(),
                "schema": schema,
                "threads": 8,
            }
        elif warehouse is Warehouse.BIGQUERY:
            outputs[environment] = {
                "type": "bigquery",
                "method": "oauth",
                "project": "{{ env_var('BIGQUERY_PROJECT') }}",
                "dataset": schema,
                "threads": 8,
            }
        else:
            outputs[environment] = {
                "type": plan.target.adapter.removeprefix("dbt-"),
                "host": "{{ env_var('DB_HOST') }}",
                "user": "{{ env_var('DB_USER') }}",
                "password": "{{ env_var('DB_PASSWORD') }}",
                "port": 5439 if warehouse is Warehouse.REDSHIFT else 5432,
                "dbname": database.lower(),
                "schema": schema,
                "threads": 4,
            }
    default = manifest.targets.environments[0] if manifest.targets.environments else "dev"
    return {name: {"target": default, "outputs": outputs}}


def _is_file(database: str | None) -> bool:
    return bool(database) and ("/" in database or database.endswith((".duckdb", ".db")))


def warehouse_database(manifest) -> str:
    """The warehouse database to build in: the manifest's, unless that is a DuckDB file name."""
    configured = manifest.targets.warehouse.database
    if configured and not _is_file(configured):
        return configured
    return manifest.project.name.upper()


def _readme(plan: Plan) -> str:
    name = plan.project.manifest.project.name
    staging = sum(m.layer == "staging" for m in plan.models)
    modelled = len(plan.models) - staging
    return (
        f"# {name} dbt project\n\n"
        "Generated by Murakumo. Everything in this folder is rewritten by `murakumo generate`;\n"
        "change the model under `model/` instead, and put hand-written dbt code in `custom/`.\n\n"
        f"- {len(plan.sources)} source(s), {staging} staging model(s), {modelled} modelled model(s), "
        f"{len(plan.snapshots)} snapshot(s)\n"
        f"- Warehouse: {plan.target.warehouse.value} (`pip install {plan.target.adapter}`)\n\n"
        "```bash\n"
        "dbt build --profiles-dir .\n"
        "```\n\n"
        "Credentials come from environment variables named in `profiles.yml`; nothing secret is stored here.\n"
    )
