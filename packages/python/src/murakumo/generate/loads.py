"""Loading landed files into the raw tables with nothing but SQL: what ``murakumo load`` does, by hand.

One script per raw table, for DuckDB and Snowflake, reading the files under
``<landing>/<source>/<table>/`` (run them from the project folder). Each loads the table its own
way, as ``murakumo load`` does:

- ``append``: every file not loaded before is added;
- ``incremental``: the new rows replace the rows with the same key, the latest of each key kept;
- ``full``: the latest run's files replace the table, once that run is new.

DuckDB remembers each file it loaded in ``audit.loaded_files``, by name (file names carry the run's
time, so a name is never reused). Snowflake's COPY remembers the files it loaded itself.
"""

from __future__ import annotations

from murakumo import loading
from murakumo.generate.plan import Plan, quote_identifier
from murakumo.ir.model import Entity

HEADER = "-- Generated by Murakumo: {what}, without Murakumo. Run it from the project folder.\n"
RUN = r"_(\d{8}T\d{12}Z)_"  # the run's time in a landed file's name: <table>_<run>_...
AUDIT = "audit"


def _formats(project) -> dict[str, tuple[str, str]]:
    """Each connected raw table's landed files: (format, glob within its folder)."""
    from murakumo.ingest import connected

    out: dict[str, tuple[str, str]] = {}
    for declaration in connected(project):
        connection = declaration.connection
        sets = getattr(connection, "files", None) or []
        for table in declaration.tables():
            found = next((f for f in sets if f.table == table), None)
            pattern = found.pattern if found else None
            suffix = pattern.rsplit(".", 1)[-1].lower() if pattern and "." in pattern else "jsonl"
            if found is not None and getattr(found, "format", None):
                suffix = found.format
            fmt = {"csv": "csv", "tsv": "csv", "parquet": "parquet"}.get(suffix, "json")
            if connection.kind == "kafka":  # the consumer's files, or a streaming engine's part files
                from murakumo.generate.streaming import landing_glob

                out[table] = ("json", landing_glob(table))
                continue
            out[table] = (fmt, f"{table}_*.{suffix}" if pattern else f"{table}_*.jsonl")
    return out


def tables(plan: Plan) -> list[tuple[str, str, Entity, str, str, str]]:
    """(source, schema, entity, mode, format, folder) for every raw table, in source then name order."""
    project = plan.project
    formats = _formats(project)
    landing = project.manifest.stack.landing.rstrip("/")
    out = []
    for group in plan.sources:
        for table in group.tables:
            entity = table.entity
            source = entity.source or "raw"
            fmt, pattern = formats.get(entity.name, ("json", f"{entity.name}_*.jsonl"))
            folder = f"{landing}/{source}/{entity.name}"
            out.append((source, group.schema, entity, loading.mode(entity), fmt, f"{folder}/{pattern}"))
    return out


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


class DuckDB:
    dialect = "duckdb"

    def __init__(self, plan: Plan):
        self.plan = plan
        self.text = plan.project.manifest.modelling.raw_columns == "text"

    def q(self, name: str) -> str:
        return quote_identifier(name, self.dialect)

    def type_of(self, attribute) -> str:
        return "VARCHAR" if self.text else self.plan.target.physical(attribute.logical_type)

    def reader(self, entity: Entity, fmt: str, files: str) -> str:
        types = ", ".join(f"{_literal(a.name)}: {_literal(self.type_of(a))}" for a in entity.attributes)
        if fmt == "csv":
            return f"read_csv({_literal(files)}, header = true, filename = true, types = {{{types}}})"
        if fmt == "parquet":
            return f"read_parquet({_literal(files)}, filename = true)"
        return f"read_json({_literal(files)}, format = 'newline_delimited', filename = true, columns = {{{types}}})"

    def script(self, source: str, schema: str, entity: Entity, mode: str, fmt: str, files: str) -> str:
        table = f"{self.q(schema)}.{self.q(entity.name)}"
        name = _literal(entity.name)
        columns = ", ".join(self.q(a.name) for a in entity.attributes)
        selected = ", ".join(
            f"cast({self.q(a.name)} as {self.type_of(a)}) as {self.q(a.name)}" for a in entity.attributes
        )
        seen = (
            f"parse_filename(filename) not in (select parse_filename(path) from {AUDIT}.loaded_files "
            f"where table_name = {name})"
        )
        lines = [
            HEADER.format(what=f"load {source}.{entity.name} ({mode})"),
            f"-- The files under {files.rsplit('/', 1)[0]}/ that were not loaded before.",
        ]
        if mode == "full":
            latest = f"(select max(regexp_extract(file, '{RUN}', 1)) from glob({_literal(files)}))"
            lines += [
                "-- Loaded in full: each run fetched the whole table, so only the latest run's files count.",
                f"create or replace temp table new_rows as\nselect {selected}, filename\n"
                f"from {self.reader(entity, fmt, files)}",
                f"where regexp_extract(filename, '{RUN}', 1) = {latest}\n  and {seen};",
                "-- When the latest run is new, its rows replace the table's.",
                f"delete from {table} where exists (select 1 from new_rows);",
                f"insert into {table} ({columns}, _ingested_at, _batch_id)\n"
                f"select {columns}, now(), parse_filename(filename) from new_rows;",
            ]
        else:
            lines.append(
                f"create or replace temp table new_rows as\nselect {selected}, filename\n"
                f"from {self.reader(entity, fmt, files)}\nwhere {seen};"
            )
            keys = [self.q(k) for k in loading.keys(entity)]
            if mode == "incremental" and keys:
                listed = ", ".join(keys)
                latest = self.q(entity.watermark) if entity.watermark else "filename"
                lines += [
                    "-- Incremental: the new rows replace the rows with the same key; the latest of each key is kept.",
                    f"delete from {table} where ({listed}) in (select {listed} from new_rows);",
                    f"insert into {table} ({columns}, _ingested_at, _batch_id)\n"
                    f"select {columns}, now(), parse_filename(filename) from new_rows\n"
                    f"qualify row_number() over (partition by {listed} order by {latest} desc nulls last) = 1;",
                ]
            else:
                lines += [
                    "-- Append: the new files' rows are added.",
                    f"insert into {table} ({columns}, _ingested_at, _batch_id)\n"
                    f"select {columns}, now(), parse_filename(filename) from new_rows;",
                ]
        lines += [
            "-- Remember the files, so the next run skips them.",
            f"insert into {AUDIT}.loaded_files (table_name, path, size, sha256, rows_ingested, batch_id, loaded_at)\n"
            f"select {name}, filename, null, null, count(*), parse_filename(filename), now()\n"
            "from new_rows group by filename;",
            "drop table new_rows;",
        ]
        return "\n".join(lines) + "\n"

    def setup(self) -> str:
        return HEADER.format(what="where loaded files are remembered") + loading.loaded_files_sql(self.dialect, AUDIT)


class Snowflake:
    dialect = "snowflake"

    def __init__(self, plan: Plan):
        self.plan = plan
        self.text = plan.project.manifest.modelling.raw_columns == "text"
        self.s3 = "://" in plan.project.manifest.stack.landing

    def q(self, name: str) -> str:
        return quote_identifier(name, self.dialect)

    def script(self, source: str, schema: str, entity: Entity, mode: str, fmt: str, files: str) -> str:
        from murakumo.generate.ingestion import _columns

        table = f"{self.q(schema)}.{self.q(entity.name)}"
        folder, pattern = files.rsplit("/", 1)
        if self.s3:
            stage = f"@RAW_LANDING.LANDING/{source}/{entity.name}/"
            staging = [
                "-- The files are read where they landed, through the stage Snowpipe uses",
                "-- (generated/ingestion/snowpipe/<env>.sql creates it).",
            ]
        else:
            stage = f"@{self.q(schema)}.%{self.q(entity.name)}"
            staging = [
                "-- Upload the files to the table's own stage (PUT runs in SnowSQL or the Snowflake CLI:",
                "-- `snow sql -f <this file>`). Files already uploaded are skipped.",
            ]
        if fmt == "json":
            pairs = _columns(self.plan, entity)
            target = ", ".join(c for c, _ in pairs)
            source_sql = f"(select {', '.join(v for _, v in pairs)}\n      from {stage})"
            file_format = "type = json"
        else:
            target, source_sql = "", stage
            file_format = (
                "type = parquet"
                if fmt == "parquet"
                else "type = csv parse_header = true field_optionally_enclosed_by = '\"'"
            )
        match = "" if fmt == "json" else "\n  match_by_column_name = case_insensitive"
        into = f"{table} ({target})" if target else table
        lines = [HEADER.format(what=f"load {source}.{entity.name} ({mode})"), *staging]
        if mode == "full":
            lines += [
                "-- Loaded in full: each run fetched the whole table, so only the latest run's files count.",
                f"-- Put the newest run's time (in the file names: ls {folder} | tail -1) in place of <run>.",
            ]
            if not self.s3:
                lines += [
                    f"remove {stage};",
                    f"put 'file://{folder}/{entity.name}_<run>_*' {stage} auto_compress = true;",
                ]
            lines += [
                f"truncate table {table};",
                f"copy into {into}\n  from {source_sql}\n  file_format = ({file_format}){match}"
                + ("" if not self.s3 else f"\n  pattern = '.*{entity.name}_<run>_.*'")
                + "\n  force = true\n  on_error = continue;",
            ]
            return "\n".join(lines) + "\n"
        if not self.s3:
            lines.append(f"put 'file://{folder}/{pattern}' {stage} auto_compress = true overwrite = false;")
        keys = [self.q(k) for k in loading.keys(entity)]
        copy = "-- COPY loads only the files it has not loaded before (it remembers them for 64 days)."
        if mode == "incremental" and keys:
            work = f"{self.q(schema)}.{self.q(entity.name + '__new')}"
            listed = ", ".join(keys)
            latest = self.q(entity.watermark) if entity.watermark else "_ingested_at"
            into_work = f"{work} ({target})" if target else work
            lines += [
                f"create transient table if not exists {work} like {table};",
                f"truncate table {work};",
                copy,
                f"copy into {into_work}\n  from {source_sql}\n  file_format = ({file_format}){match}\n"
                "  on_error = continue;",
                "-- Incremental: the new rows replace the rows with the same key; the latest of each key is kept.",
                f"delete from {table} where ({listed}) in (select {listed} from {work});",
                f"insert into {table}\nselect * from {work}\n"
                f"qualify row_number() over (partition by {listed} order by {latest} desc nulls last) = 1;",
            ]
        else:
            lines += [
                copy,
                f"copy into {into}\n  from {source_sql}\n  file_format = ({file_format}){match}\n"
                "  on_error = continue;",
            ]
        return "\n".join(lines) + "\n"

    def setup(self) -> str:
        return ""


LOADERS = {"duckdb": DuckDB, "snowflake": Snowflake}


def render(plan: Plan) -> dict[str, str]:
    """The load scripts for the plan's warehouse, by file name (none for other warehouses)."""
    loader = LOADERS.get(plan.target.dialect)
    if loader is None:
        return {}
    writer = loader(plan)
    found = tables(plan)
    files: dict[str, str] = {}
    setup = writer.setup()
    if setup:
        files["00_audit.sql"] = setup
    width = max(2, len(str(len(found))))
    for index, (source, schema, entity, mode, fmt, glob) in enumerate(found, start=1):
        files[f"{index:0{width}d}_{schema}__{entity.name}.sql"] = writer.script(source, schema, entity, mode, fmt, glob)
    return files


__all__ = ["render", "tables"]
