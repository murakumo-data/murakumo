"""DDL per warehouse.

- ``raw.sql`` creates the landing schemas and tables that ingestion writes into, with the
  landing audit columns. Raw tables carry no constraints, not even NOT NULL: sources send
  duplicates and gaps, and the staging tests report them instead of the load failing.
- ``marts.sql`` is the reference DDL for the modelled tables, with primary and foreign keys.
  dbt builds these tables; this file is for catalogues, reviews and teams that do not use dbt.
  Keys are informational where the warehouse does not enforce them.
"""

from __future__ import annotations

from uuid import UUID

from murakumo.generate.plan import LANDING_COLUMNS, Plan, quote_identifier
from murakumo.ir.model import Entity, Layer
from murakumo.ir.types import parse_type
from murakumo.manifest import Warehouse

HEADER = "-- Generated by Murakumo for {warehouse}. Do not edit: change the model, then run `murakumo generate`.\n"


def _comment(text: str | None, backslash: bool = False) -> str:
    """Text for a quoted SQL string. BigQuery and Databricks escape a quote with \\, the rest double it."""
    text = (text or "").replace("\n", " ")
    if backslash:
        return text.replace("\\", "\\\\").replace("'", "\\'")
    return text.replace("'", "''")


class DDL:
    def __init__(self, plan: Plan, schema_prefix: str = ""):
        self.plan = plan
        self.prefix = schema_prefix
        self.target = plan.target
        self.dialect = plan.target.dialect
        self.warehouse = plan.target.warehouse
        self.blocks: dict[UUID, str] = {}  # each entity's statements, for showing next to it

    def q(self, name: str) -> str:
        return quote_identifier(name, self.dialect)

    def inline_comments(self) -> bool:
        return self.warehouse in (Warehouse.DATABRICKS, Warehouse.BIGQUERY)

    def column(self, name: str, data_type: str, nullable: bool, comment: str | None) -> str:
        sql = f"    {self.q(name)} {data_type}"
        if not nullable:
            sql += " NOT NULL"
        if comment and self.warehouse is Warehouse.DATABRICKS:
            sql += f" COMMENT '{_comment(comment, True)}'"
        elif comment and self.warehouse is Warehouse.BIGQUERY:
            sql += f" OPTIONS(description='{_comment(comment, True)}')"
        return sql

    def table(
        self,
        schema: str,
        entity: Entity,
        columns: list[tuple[str, str, bool, str | None]],
        constraints: list[str],
        name: str | None = None,
    ) -> str:
        table = f"{self.q(schema)}.{self.q(name or entity.name)}"
        lines = [self.column(*c) for c in columns] + [f"    {c}" for c in constraints]
        sql = f"CREATE TABLE IF NOT EXISTS {table} (\n" + ",\n".join(lines) + "\n)"
        if entity.description and self.warehouse is Warehouse.DATABRICKS:
            sql += f"\nCOMMENT '{_comment(entity.description, True)}'"
        if entity.description and self.warehouse is Warehouse.BIGQUERY:
            sql += f"\nOPTIONS(description='{_comment(entity.description, True)}')"
        sql += ";\n"
        if not self.inline_comments() and self.warehouse not in (Warehouse.FABRIC, Warehouse.SYNAPSE):
            if entity.description:
                sql += f"COMMENT ON TABLE {table} IS '{_comment(entity.description)}';\n"
            for column_name, _type, _nullable, comment in columns:
                if comment:
                    sql += f"COMMENT ON COLUMN {table}.{self.q(column_name)} IS '{_comment(comment)}';\n"
        self.blocks[entity.id] = sql
        return sql

    def schema(self, name: str) -> str:
        keyword = "DATASET" if self.warehouse is Warehouse.BIGQUERY else "SCHEMA"
        if self.warehouse in (Warehouse.FABRIC, Warehouse.SYNAPSE):
            return f"IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = '{name}') EXEC('CREATE SCHEMA {name}');\n"
        return f"CREATE {keyword} IF NOT EXISTS {self.q(name)};\n"

    def raw(self) -> str:
        out = [HEADER.format(warehouse=self.warehouse.value)]
        for group in self.plan.sources:
            out.append(f"\n-- Source: {group.name}\n")
            out.append(self.schema(self.prefix + group.schema))
            for table in group.tables:
                entity = table.entity
                # Landing tables accept whatever the source sends; staging tests catch bad rows.
                columns = [
                    (a.name, self.target.physical(a.logical_type), True, a.description) for a in entity.attributes
                ]
                columns += [
                    (name, self.target.physical(parse_type(logical)), True, "Written by ingestion.")
                    for name, logical in LANDING_COLUMNS.items()
                ]
                out.append("\n" + self.table(self.prefix + group.schema, entity, columns, []))
        return "".join(out)

    def key_suffix(self) -> str:
        if self.warehouse in (Warehouse.DATABRICKS, Warehouse.BIGQUERY):
            return " NOT ENFORCED"
        if self.warehouse is Warehouse.SNOWFLAKE:
            return " RELY"
        return ""

    def marts(self) -> str:
        out = [HEADER.format(warehouse=self.warehouse.value)]
        out.append("-- Reference DDL: dbt builds these tables. Keys are informational where not enforced.\n")
        modelled = [
            m
            for m in self.plan.models
            if m.layer not in ("staging", "intermediate") and m.entity.layer is not Layer.RAW
        ]
        by_name = {m.entity.name.lower(): m for m in modelled}
        schemas = sorted({m.layer for m in modelled})
        for schema in schemas:
            out.append(self.schema(schema))
        suffix = self.key_suffix()
        for model in modelled:
            entity = model.entity
            columns = [(c.name, c.data_type, _nullable(entity, c.name), c.description) for c in model.columns]
            constraints = []
            keys = [a.name for a in entity.primary_key]
            if model.entity.history.value in ("scd2", "scd6") and keys:
                keys = [*keys, "valid_from"]
            if keys and self.warehouse is not Warehouse.DUCKDB:
                constraints.append(f"PRIMARY KEY ({', '.join(self.q(k) for k in keys)}){suffix}")
            for rel in self.plan.project.model.relationships:
                parent = by_name.get(rel.to.lower())
                if rel.from_.lower() != entity.name.lower() or parent is None or self.warehouse is Warehouse.DUCKDB:
                    continue
                left = ", ".join(self.q(k.from_) for k in rel.keys)
                right = ", ".join(self.q(k.to) for k in rel.keys)
                constraints.append(
                    f"FOREIGN KEY ({left}) REFERENCES {self.q(parent.layer)}.{self.q(parent.name)} ({right}){suffix}"
                )
            out.append("\n" + self.table(model.layer, entity, columns, constraints, name=model.name))
        if self.warehouse is Warehouse.DUCKDB:
            out.append("\n-- DuckDB enforces keys, so dbt tests check them instead of constraints here.\n")
        return "".join(out)


def _nullable(entity: Entity, column: str) -> bool:
    attribute = entity.attribute(column)
    return attribute.nullable if attribute is not None else True


def render(plan: Plan, ddl: DDL | None = None) -> dict[str, str]:
    ddl = ddl or DDL(plan)
    files = {"raw.sql": ddl.raw()}
    if any(m.layer not in ("staging", "intermediate") for m in plan.models):
        files["marts.sql"] = ddl.marts()
    return files
