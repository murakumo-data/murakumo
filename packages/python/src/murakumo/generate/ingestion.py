"""Ingestion: the code that fetches each source's data and loads it, for the stack's tools.

Written under ``generated/ingestion/`` for every source in murakumo.yaml with a ``connection``:

- ``python/``: ``extract.py`` (standalone, the standard library for REST and folders) and one
  settings file per source. Every extract choice runs these: on a schedule's worker (python), as
  Lambda functions (lambda), or as Glue Python shell jobs (glue).
- ``lambda/``: an AWS SAM template, one function per source on its own schedule.
- ``glue/``: a Glue job per source (Spark over JDBC for databases), and the commands to create them.
- ``snowpipe/``: the storage integration, stage, file format and one pipe per raw table, per
  environment, for load: snowpipe.
- ``autoloader/``: a Databricks notebook per source, for load: autoloader.

Each part also says how to set it up, step by step, in ``steps()``: the pipeline documentation
prints them, so the platform can be rebuilt by hand without Murakumo.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from importlib import resources
from typing import Any

import yaml

from murakumo.generate.ddl import DDL
from murakumo.generate.plan import LANDING_COLUMNS, Plan, quote_identifier, snake
from murakumo.ir.model import Entity
from murakumo.manifest import SourceDeclaration

PY_HEADER = '"""Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n\n{doc}\n"""\n'
YAML_HEADER = "# Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n"
SQL_HEADER = "-- Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n"

# generated/ingestion/python/sources/<source>.json -> the project folder
ROOT_FROM_SETTINGS = "../../../.."
REQUIREMENTS = {
    "rest": [],
    "files": [],
    "sftp": ["paramiko>=3.4"],
    "database": ["sqlalchemy>=2.0"],
    "protobuf": ["protobuf>=5.27", "grpcio-tools>=1.64"],
    "kafka": ["kafka-python>=2.0"],
}


@dataclass
class Step:
    """One thing to do, by hand, to set the platform up."""

    key: str
    title: str
    why: str
    commands: list[str] = field(default_factory=list)  # shell
    sql: str | None = None
    files: list[str] = field(default_factory=list)  # under generated/


def connected(project) -> list[SourceDeclaration]:
    return [d for d in project.manifest.sources if d.connection is not None]


def settings(project, declaration: SourceDeclaration) -> dict[str, Any]:
    """The settings file extract.py reads for a source."""
    watermarks = {}
    for table in declaration.tables():
        entity = project.model.entity(table)
        if entity is not None and entity.watermark:
            watermarks[table] = entity.watermark
    connection = declaration.connection.model_dump(exclude_none=True)  # type: ignore[union-attr]
    for query in connection.get("tables", []):  # databases: the model's watermark unless one is given
        query.setdefault("incremental_column", watermarks.get(query["table"]))
        if query["incremental_column"] is None:
            del query["incremental_column"]
    return {
        "source": declaration.name,
        "root": ROOT_FROM_SETTINGS,
        "landing": project.manifest.stack.landing,
        "connection": connection,
        "watermarks": watermarks,
    }


def _raw_tables(plan: Plan) -> dict[str, tuple[str, Entity]]:
    return {t.entity.name: (g.schema, t.entity) for g in plan.sources for t in g.tables}


def render(project, plan: Plan) -> dict[str, str]:
    """Files under generated/ingestion/, keyed by their path below generated/."""
    stack = project.manifest.stack
    sources = connected(project)
    if not sources:
        return {}
    files: dict[str, str] = {}
    if stack.extract != "none":
        files.update(_python(project, sources))
    if stack.extract == "lambda":
        files.update(_lambda(project, sources))
    if stack.extract == "glue":
        files.update(_glue(project, sources))
    if stack.load == "snowpipe":
        files.update(_snowpipe(project, plan, sources))
    if stack.load == "autoloader":
        files.update(_autoloader(project, plan, sources))
    files["ingestion/README.md"] = _readme(project, steps(project, plan))
    return files


# Python ---------------------------------------------------------------------------------------


def _python(project, sources: list[SourceDeclaration]) -> dict[str, str]:
    runtime = resources.files("murakumo").joinpath("extract.py").read_text(encoding="utf-8")
    files = {"ingestion/python/extract.py": runtime}
    needs: list[str] = []
    for declaration in sources:
        files[f"ingestion/python/sources/{declaration.name}.json"] = (
            json.dumps(settings(project, declaration), indent=2) + "\n"
        )
        needs += REQUIREMENTS[declaration.connection.kind]  # type: ignore[union-attr]
    if project.manifest.stack.landing.startswith("s3://") or any(
        "s3://" in getattr(d.connection, "location", "") for d in sources
    ):
        needs.append("boto3>=1.34")
    files["ingestion/python/requirements.txt"] = (
        "".join(f"{r}\n" for r in sorted(set(needs))) or "# none: the standard library is enough\n"
    )
    return files


# AWS Lambda -----------------------------------------------------------------------------------


def _schedule_expression(declaration: SourceDeclaration) -> str:
    """A Lambda schedule: the source's ingestion schedule if it is a cron line, else hourly."""
    cron = declaration.ingestion.schedule
    if cron and len(cron.split()) == 5:
        minute, hour, day, month, weekday = cron.split()
        if day != "*" and weekday != "*":
            weekday = "?"
        elif weekday == "*":
            weekday = "?"
        else:
            day = "?"
        return f"cron({minute} {hour} {day} {month} {weekday} *)"
    return {"daily": "rate(1 day)", "hourly": "rate(1 hour)", "weekly": "rate(7 days)"}.get(cron or "", "rate(1 hour)")


def _bucket(landing: str) -> str:
    return landing.removeprefix("s3://").split("/", 1)[0]


def _lambda(project, sources: list[SourceDeclaration]) -> dict[str, str]:
    landing = project.manifest.stack.landing
    secrets = sorted({v for d in sources for v in _secret_names(d)})
    functions: dict[str, Any] = {}
    for declaration in sources:
        functions[f"Extract{''.join(p.title() for p in declaration.name.split('_'))}"] = {
            "Type": "AWS::Serverless::Function",
            "Properties": {
                "FunctionName": f"{snake(project.manifest.project.name)}-extract-{declaration.name}".replace("_", "-"),
                "Description": f"Fetch new {declaration.name} data into {landing}",
                "CodeUri": "../python/",
                "Handler": "extract.handler",
                "Environment": {"Variables": {"MURAKUMO_SOURCE": declaration.name, "MURAKUMO_LANDING": landing}},
                "Policies": [{"S3CrudPolicy": {"BucketName": _bucket(landing)}}],
                "Events": {
                    "Schedule": {"Type": "Schedule", "Properties": {"Schedule": _schedule_expression(declaration)}}
                },
            },
        }
    template = {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Transform": "AWS::Serverless-2016-10-31",
        "Description": f"Extract functions for {project.manifest.project.name}, written by Murakumo",
        "Globals": {
            "Function": {
                "Runtime": "python3.12",
                "Timeout": 900,
                "MemorySize": 512,
                "Environment": {"Variables": {name: {"Ref": _parameter(name)} for name in secrets}},
            }
        },
        "Resources": functions,
    }
    if secrets:  # asked for by `sam deploy --guided`, and never shown or stored in the template
        template = {
            **{k: v for k, v in template.items() if k != "Globals" and k != "Resources"},
            "Parameters": {
                _parameter(name): {"Type": "String", "NoEcho": True, "Description": f"The value of {name}"}
                for name in secrets
            },
            "Globals": template["Globals"],
            "Resources": functions,
        }
    return {"ingestion/lambda/template.yaml": YAML_HEADER + yaml.safe_dump(template, sort_keys=False)}


def _parameter(name: str) -> str:
    return "".join(part.title() for part in name.lower().split("_"))


def _secret_names(declaration: SourceDeclaration) -> list[str]:
    data = declaration.connection.model_dump(exclude_none=True)  # type: ignore[union-attr]
    names: list[str] = []

    def walk(value: Any, key: str = "") -> None:
        if isinstance(value, dict):
            for k, v in value.items():
                walk(v, k)
        elif isinstance(value, list):
            for v in value:
                walk(v, key)
        elif key == "env" or key.endswith("_env"):
            names.append(str(value))

    walk(data)
    return names


# AWS Glue -------------------------------------------------------------------------------------


def _glue(project, sources: list[SourceDeclaration]) -> dict[str, str]:
    landing = project.manifest.stack.landing.rstrip("/")
    scripts = f"s3://{_bucket(landing)}/murakumo/glue"
    name = snake(project.manifest.project.name).replace("_", "-")
    files: dict[str, str] = {}
    commands = [
        "# Upload the scripts, then create (or update) each job and its schedule.",
        f"aws s3 cp ../python/extract.py {scripts}/extract.py",
        f"aws s3 cp ../python/sources/ {scripts}/sources/ --recursive",
    ]
    for declaration in sources:
        job = f"{name}-extract-{declaration.name.replace('_', '-')}"
        spark = declaration.connection.kind == "database"  # type: ignore[union-attr]
        script = f"{declaration.name}.py"
        if spark:
            files[f"ingestion/glue/{script}"] = _glue_spark(project, declaration)
            command = {"Name": "glueetl", "ScriptLocation": f"{scripts}/{script}", "PythonVersion": "3"}
            extra = {"--conf": "spark.sql.sources.partitionOverwriteMode=dynamic"}
        else:
            files[f"ingestion/glue/{script}"] = (
                PY_HEADER.format(doc=f"AWS Glue Python shell job: fetch new {declaration.name} data into {landing}.")
                + f"""
import json
import sys
from pathlib import Path

import boto3

import extract  # uploaded beside this job with --extra-py-files

s3 = boto3.client("s3")
folder = Path("/tmp/murakumo/sources")
folder.mkdir(parents=True, exist_ok=True)
settings_file = folder / "{declaration.name}.json"
s3.download_file({json.dumps(_bucket(landing))}, "murakumo/glue/sources/{declaration.name}.json", str(settings_file))
settings = json.loads(settings_file.read_text())
for table, (count, files) in extract.run(settings, landing={json.dumps(landing)}).items():
    print(f"{declaration.name}.{{table}}: {{count}} new, {{len(files)}} file(s) landed")
sys.exit(0)
"""
            )
            command = {"Name": "pythonshell", "ScriptLocation": f"{scripts}/{script}", "PythonVersion": "3.9"}
            extra = {
                "--extra-py-files": f"{scripts}/extract.py",
                "--additional-python-modules": ",".join(
                    REQUIREMENTS[declaration.connection.kind] or ["boto3"]  # type: ignore[union-attr]
                ),
            }
        definition = {
            "Name": job,
            "Description": f"Fetch new {declaration.name} data into {landing}",
            "Role": "MurakumoGlueRole",
            "Command": command,
            "DefaultArguments": {"--job-language": "python", **extra},
            "MaxRetries": 1,
            "Timeout": 120,
            **(
                {"GlueVersion": "4.0", "WorkerType": "G.1X", "NumberOfWorkers": 2} if spark else {"MaxCapacity": 0.0625}
            ),
        }
        files[f"ingestion/glue/jobs/{declaration.name}.json"] = json.dumps(definition, indent=2) + "\n"
        commands += [
            f"aws s3 cp {script} {scripts}/{script}",
            f"aws glue create-job --cli-input-json file://jobs/{declaration.name}.json"
            f" || aws glue update-job --job-name {job}"
            f" --job-update \"$(jq 'del(.Name)' jobs/{declaration.name}.json)\"",
            f"aws glue create-trigger --name {job}-schedule --type SCHEDULED"
            f" --schedule '{_schedule_expression(declaration)}' --actions JobName={job} --start-on-creation || true",
        ]
    files["ingestion/glue/deploy.sh"] = (
        "#!/usr/bin/env bash\n# Generated by Murakumo. Run from generated/ingestion/glue, with AWS credentials set.\n"
        'set -euo pipefail\ncd "$(dirname "$0")"\n' + "\n".join(commands) + "\n"
    )
    return files


def _glue_spark(project, declaration: SourceDeclaration) -> str:
    c = declaration.connection
    landing = project.manifest.stack.landing.rstrip("/")
    tables = [
        {
            "table": q.table,
            "source": q.source,
            "column": q.incremental_column or (project.model.entity(q.table) or Entity(name="x")).watermark,
        }
        for q in c.tables  # type: ignore[union-attr]
    ]
    return (
        PY_HEADER.format(
            doc=f"AWS Glue Spark job: copy new rows of {declaration.name}'s tables into {landing} as Parquet."
        )
        + f"""
import json
import os
import sys

from awsglue.context import GlueContext
from awsglue.utils import getResolvedOptions
from pyspark.context import SparkContext
from pyspark.sql import functions as F

args = getResolvedOptions(sys.argv, ["JOB_NAME"])
spark = GlueContext(SparkContext.getOrCreate()).spark_session
# The JDBC URL (jdbc:postgresql://host:5432/db), user and password, from the job's parameters
# or a Glue connection: never written here.
URL, USER, PASSWORD = os.environ["SOURCE_JDBC_URL"], os.environ["SOURCE_USER"], os.environ["SOURCE_PASSWORD"]
LANDING = {json.dumps(landing + "/" + declaration.name)}
TABLES = {json.dumps(tables, indent=4)}

for table in TABLES:
    query = table["source"] if table["source"].lower().startswith("select") else f"select * from {{table['source']}}"
    target = f"{{LANDING}}/{{table['table']}}"
    if table["column"]:
        try:
            latest = spark.read.parquet(target).agg(F.max(table["column"])).first()[0]
        except Exception:  # nothing landed yet
            latest = None
        if latest is not None:
            query = f"select * from ({{query}}) as source where {{table['column']}} > '{{latest}}'"
    rows = (
        spark.read.format("jdbc")
        .option("url", URL).option("user", USER).option("password", PASSWORD)
        .option("query", query).option("fetchsize", 10000)
        .load()
    )
    rows.write.mode("append").parquet(target)
    print(f"{{table['table']}}: {{rows.count()}} new row(s)")
"""
    )


# Snowpipe ---------------------------------------------------------------------------------------


def _columns(plan: Plan, entity: Entity) -> list[tuple[str, str]]:
    """Each raw column and the value a COPY puts in it, from a JSON line ($1)."""
    text = plan.project.manifest.modelling.raw_columns == "text"
    pairs = []
    for attribute in entity.attributes:
        physical = "VARCHAR" if text else plan.target.physical(attribute.logical_type)
        key = attribute.name.replace('"', '""')
        pairs.append((quote_identifier(attribute.name, "snowflake"), f'$1:"{key}"::{physical}'))
    metadata = {"_ingested_at": "METADATA$START_SCAN_TIME", "_batch_id": "METADATA$FILENAME"}
    for name in LANDING_COLUMNS:
        pairs.append((name, metadata.get(name, "NULL")))
    return pairs


def _environment_databases(project) -> list[tuple[str, str]]:
    from murakumo.generate.dbt import warehouse_database

    default = warehouse_database(project.manifest).upper()
    return [(e.name, (e.database or default).upper()) for e in project.manifest.targets.environments]


def snowpipe_sql(project, plan: Plan, environment: str) -> str:
    """The stage, file format and pipes for one environment."""
    name = project.manifest.project.name.upper()
    database = dict(_environment_databases(project))[environment]
    landing = project.manifest.stack.landing.rstrip("/")
    raw = _raw_tables(plan)
    stage = f"{database}.RAW_LANDING.LANDING"
    lines = [
        SQL_HEADER,
        f"-- Snowpipe for {project.manifest.project.name}, {environment}: each file that lands in {landing}",
        "-- is loaded into its raw table within a minute. Run as the environment's deployer role, after",
        "-- integration.sql and `murakumo env provision`. Each statement can run again safely.",
        "",
        f"create schema if not exists {database}.RAW_LANDING;",
        f"create file format if not exists {database}.RAW_LANDING.JSON_LINES type = json strip_outer_array = false;",
        f"create stage if not exists {stage}",
        f"  url = '{landing}/'",
        f"  storage_integration = {name}_LANDING",
        f"  file_format = {database}.RAW_LANDING.JSON_LINES;",
        "",
        "-- The raw tables the pipes load (generated/ddl/snowflake/raw.sql, in this database).",
        f"use database {database};",
        *[line for line in DDL(plan).raw().splitlines() if not line.startswith("-- Generated by Murakumo")],
    ]
    for declaration in connected(project):
        for table in declaration.tables():
            if table not in raw:
                continue
            schema, entity = raw[table]
            pairs = _columns(plan, entity)
            target = f"{database}.{schema.upper()}.{quote_identifier(entity.name, 'snowflake').upper()}"
            pipe = f"{database}.{schema.upper()}.{entity.name.upper()}_PIPE"
            lines += [
                "",
                f"-- {declaration.name}.{table}: files under {landing}/{declaration.name}/{table}/",
                f"create schema if not exists {database}.{schema.upper()};",
                f"create pipe if not exists {pipe} auto_ingest = true as",
                f"  copy into {target} ({', '.join(c for c, _ in pairs)})",
                f"  from (select {', '.join(v for _, v in pairs)}",
                f"        from @{stage}/{declaration.name}/{table}/)",
                "  on_error = continue;",
            ]
    lines += [
        "",
        "-- The S3 bucket sends a notification to each pipe's queue (the same queue for every pipe):",
        "-- show pipes; copy notification_channel into the bucket's event notification (all object create events).",
        "-- Files that landed before the pipes existed: alter pipe <pipe> refresh;",
    ]
    return "\n".join(lines) + "\n"


def _snowpipe(project, plan: Plan, sources: list[SourceDeclaration]) -> dict[str, str]:
    name = project.manifest.project.name.upper()
    landing = project.manifest.stack.landing.rstrip("/")
    integration = "\n".join(
        [
            SQL_HEADER,
            f"-- Once, as ACCOUNTADMIN: let Snowflake read {landing} through an AWS role, without keys.",
            f"create storage integration if not exists {name}_LANDING",
            "  type = external_stage",
            "  storage_provider = 's3'",
            "  enabled = true",
            "  storage_aws_role_arn = 'arn:aws:iam::<account id>:role/<role Snowflake assumes>'",
            f"  storage_allowed_locations = ('{landing}/');",
            "",
            "-- Then trust Snowflake in that AWS role: copy STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID",
            "-- from this into the role's trust policy.",
            f"desc integration {name}_LANDING;",
            "",
            "-- And let each environment's deployer use it:",
            *(
                f"grant usage on integration {name}_LANDING to role {name}_DEPLOYER_{env.upper()};"
                for env, _ in _environment_databases(project)
            ),
        ]
    )
    files = {"ingestion/snowpipe/integration.sql": integration + "\n"}
    for env, _ in _environment_databases(project):
        files[f"ingestion/snowpipe/{env}.sql"] = snowpipe_sql(project, plan, env)
    return files


# Databricks Auto Loader --------------------------------------------------------------------------


def _autoloader(project, plan: Plan, sources: list[SourceDeclaration]) -> dict[str, str]:
    landing = project.manifest.stack.landing.rstrip("/")
    raw = _raw_tables(plan)
    files: dict[str, str] = {}
    tasks = []
    for declaration in sources:
        tables = [
            {"table": t, "schema": raw[t][0], "columns": [a.name for a in raw[t][1].attributes]}
            for t in declaration.tables()
            if t in raw
        ]
        files[f"ingestion/autoloader/{declaration.name}.py"] = (
            "# Databricks notebook source\n"
            + PY_HEADER.format(
                doc=f"Auto Loader: load each new {declaration.name} file from {landing} into its raw table."
            )
            + f"""
from pyspark.sql import functions as F

dbutils.widgets.text("catalog", "main")  # noqa: F821 - defined in Databricks notebooks
CATALOG = dbutils.widgets.get("catalog")  # noqa: F821
LANDING = {json.dumps(landing + "/" + declaration.name)}
CHECKPOINTS = {json.dumps(landing + "/_checkpoints/" + declaration.name)}
TABLES = {json.dumps(tables, indent=4)}

for table in TABLES:
    rows = (
        spark.readStream.format("cloudFiles")  # noqa: F821
        .option("cloudFiles.format", "json")
        .option("cloudFiles.schemaLocation", f"{{CHECKPOINTS}}/{{table['table']}}/schema")
        .option("cloudFiles.schemaEvolutionMode", "rescue")
        .load(f"{{LANDING}}/{{table['table']}}/")
    )
    (
        rows.select(
            *[F.col(f"`{{c}}`") for c in table["columns"]],
            F.current_timestamp().alias("_ingested_at"),
            F.col("_metadata.file_path").alias("_batch_id"),
        )
        .writeStream.option("checkpointLocation", f"{{CHECKPOINTS}}/{{table['table']}}")
        .option("mergeSchema", "true")
        .trigger(availableNow=True)  # load what is new, then stop
        .toTable(f"{{CATALOG}}.{{table['schema']}}.{{table['table']}}")
        .awaitTermination()
    )
"""
        )
        tasks.append(
            {
                "task_key": f"load_{declaration.name}",
                "notebook_task": {
                    "notebook_path": f"./{declaration.name}.py",
                    "base_parameters": {"catalog": "${var.catalog}"},
                },
            }
        )
    bundle = {
        "bundle": {"name": f"{snake(project.manifest.project.name)}_autoloader"},
        "variables": {"catalog": {"description": "The Unity Catalog catalog the raw tables are in", "default": "main"}},
        "resources": {
            "jobs": {
                f"{snake(project.manifest.project.name)}_load": {
                    "name": f"{project.manifest.project.name} · load",
                    "tasks": tasks,
                    "trigger": {"file_arrival": {"url": landing + "/"}, "pause_status": "PAUSED"},
                    "max_concurrent_runs": 1,
                }
            }
        },
        "targets": {"prod": {"mode": "production"}, "dev": {"mode": "development", "default": True}},
    }
    files["ingestion/autoloader/databricks.yml"] = YAML_HEADER + yaml.safe_dump(bundle, sort_keys=False)
    return files


# Setting it up, step by step ------------------------------------------------------------------------


def steps(project, plan: Plan) -> list[Step]:
    """How to set ingestion up by hand, in order, for the stack chosen."""
    stack = project.manifest.stack
    sources = connected(project)
    if not sources:
        return []
    out: list[Step] = []
    secrets = sorted({v for d in sources for v in _secret_names(d)})
    if stack.extract != "none":
        requirements = sorted({r for d in sources for r in REQUIREMENTS[d.connection.kind]})  # type: ignore[union-attr]
        out.append(
            Step(
                "secrets",
                "Set the sources' secrets",
                "Every key, token and password is read from an environment variable, never from a file"
                " in the repository.",
                [f"export {name}=..." for name in secrets] or ["# none of the sources needs a secret"],
            )
        )
        out.append(
            Step(
                "fetch",
                "Fetch each source once, by hand",
                f"Each run lands new data under {stack.landing}/<source>/<table>/ as JSON lines (or the files"
                " as they are), and remembers where it got to, so the next run fetches only what is new.",
                ([f"pip install {' '.join(requirements)}"] if requirements else [])
                + [
                    f"python generated/ingestion/python/extract.py generated/ingestion/python/sources/{d.name}.json"
                    for d in sources
                ],
                files=["ingestion/python/extract.py", *(f"ingestion/python/sources/{d.name}.json" for d in sources)],
            )
        )
    if stack.extract == "lambda":
        out.append(
            Step(
                "lambda",
                "Deploy the extract functions to AWS Lambda",
                "One function per source, each on its source's schedule, landing in S3. `sam deploy --guided`"
                " asks for each secret (a parameter that is never shown or stored in the template).",
                ["cd generated/ingestion/lambda", "sam build", "sam deploy --guided"],
                files=["ingestion/lambda/template.yaml"],
            )
        )
    if stack.extract == "glue":
        out.append(
            Step(
                "glue",
                "Create the Glue jobs",
                "One job per source with a scheduled trigger. Create the IAM role MurakumoGlueRole first, with"
                " read and write access to the landing bucket.",
                ["bash generated/ingestion/glue/deploy.sh"],
                files=["ingestion/glue/deploy.sh"],
            )
        )
    if stack.load == "snowpipe":
        out.append(
            Step(
                "integration",
                "Let Snowflake read the landing bucket",
                "A storage integration: Snowflake assumes an AWS role, so no AWS keys are stored in Snowflake.",
                sql=(_snowpipe(project, plan, sources)["ingestion/snowpipe/integration.sql"]),
                files=["ingestion/snowpipe/integration.sql"],
            )
        )
        for env, _ in _environment_databases(project):
            out.append(
                Step(
                    f"pipes-{env}",
                    f"Create the pipes in {env}",
                    "A pipe per raw table copies each new file in as it lands; then point the bucket's"
                    " event notification at the pipes' queue.",
                    sql=snowpipe_sql(project, plan, env),
                    files=[f"ingestion/snowpipe/{env}.sql"],
                )
            )
    if stack.load == "autoloader":
        out.append(
            Step(
                "autoloader",
                "Deploy the Auto Loader job",
                "A Databricks job that runs when files arrive, loading each new file into its raw table.",
                ["cd generated/ingestion/autoloader", "databricks bundle deploy -t prod"],
                files=["ingestion/autoloader/databricks.yml"],
            )
        )
    if stack.load == "build":
        target = "prod" if "prod" in project.manifest.targets.names else project.manifest.targets.names[-1]
        out.append(
            Step(
                "load",
                "Load the landed files",
                "Each file is loaded once (remembered by its content in audit.loaded_files), into its raw table"
                " the table's way: replaced, appended or merged by key. The orchestrator runs this before each build.",
                [f"murakumo load --env {target}"],
            )
        )
    return out


def _readme(project, steps_: list[Step]) -> str:
    stack = project.manifest.stack
    sources = connected(project)
    lines = [
        f"# Ingestion for {project.manifest.project.name}",
        "",
        f"Extract: **{stack.extract}** · load: **{stack.load}** · landing: `{stack.landing}`",
        "",
        "| Source | Kind | Tables |",
        "| --- | --- | --- |",
        *(f"| {d.name} | {d.connection.kind} | {', '.join(d.tables())} |" for d in sources),  # type: ignore[union-attr]
        "",
        "## Set it up",
        "",
    ]
    for number, step in enumerate(steps_, 1):
        lines += [f"### {number}. {step.title}", "", step.why, ""]
        if step.commands:
            lines += ["```bash", *step.commands, "```", ""]
        if step.sql:
            lines += [f"See `generated/{step.files[0]}`." if step.files else "", ""]
    return "\n".join(lines)


