"""Pipelines for the cloud providers' own orchestrators: AWS Step Functions, AWS Glue workflows,
Google Cloud Workflows and Azure Data Factory.

None of the four runs dbt itself, so each starts something that does: a container with the dbt
project in it (ECS on Fargate, a Cloud Run job, a Container Apps job), or for Glue a Python shell
job. Every folder has ``run.sh``, which runs one schedule, and the definitions that start it on the
schedule's cron time, as Terraform where the provider has it and as the service's own JSON where it
does not (Data Factory).
"""

from __future__ import annotations

import json

from murakumo.cron import CronError, quartz
from murakumo.generate.plan import snake

TF_HEADER = "# Generated by Murakumo. Do not edit: change murakumo.yaml, then run `murakumo generate`.\n"


def aws_cron(text: str) -> str:
    """The same time as AWS writes it (EventBridge, Glue): Quartz's fields without the seconds,
    with a year."""
    return f"cron({' '.join(quartz(text).split()[1:])} *)"


def _dockerfile(context: dict) -> str:
    return (
        "# Generated by Murakumo. Build it from the project's root: the dbt project and run.sh go in.\n"
        "#   docker build -f generated/orchestration/{folder}/Dockerfile -t {name}-dbt .\n"
        "FROM python:3.12-slim\n"
        "RUN apt-get update && apt-get install -y --no-install-recommends git && rm -rf /var/lib/apt/lists/*\n"
        "RUN pip install --no-cache-dir {adapter}\n"
        "WORKDIR /app\n"
        "COPY generated/dbt /app/dbt\n"
        "COPY generated/orchestration/{folder}/run.sh /app/run.sh\n"
        "RUN chmod +x /app/run.sh && cd /app/dbt && (dbt deps || true)\n"
        "ENV MURAKUMO_DBT_DIR=/app/dbt\n"
        'ENTRYPOINT ["/app/run.sh"]\n'
    ).format(folder=context["folder"], name=snake(context["project"]), adapter=context["adapter"])


def _schedules(context: dict, convert) -> tuple[list[tuple], list[str]]:
    """(job, converted cron) for every schedule that can be written, and a note for each that cannot."""
    found, notes = [], []
    for job in context["jobs"]:
        try:
            found.append((job, convert(job.cron)))
        except CronError as exc:
            notes.append(f"- `{job.name}`: {exc}; set its time by hand.")
    return found, notes


def _notes(notes: list[str]) -> str:
    return "\n" + "\n".join(notes) + "\n" if notes else ""


