        "each schedule's cron time (`main.tf`). Glue triggers run in UTC"
        + ("" if context["timezone"] == "UTC" else f": the times below are {context['timezone']}, so shift them")
        + ".\n\n"
        + context["table"]
        + "\n\n## Deploy\n\n"
        "```bash\n"
        f"(cd generated && zip -r /tmp/dbt.zip dbt)\n"
        f"aws s3 cp /tmp/dbt.zip s3://<bucket>/{name}/dbt.zip\n"
