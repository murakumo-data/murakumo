# Azure Data Factory ----------------------------------------------------------------------------


def _adf_recurrence(cron: str, timezone: str) -> dict | None:
    """A Data Factory schedule trigger's recurrence, for the cron times it can express: a fixed
    minute and hour, every day or on given weekdays, or every N minutes or hours."""
    minute, hour, day, month, weekday = cron.split()
    if day != "*" or month != "*":
        return None
    base = {"startTime": "2026-01-01T00:00:00", "timeZone": timezone}
    days = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"]
    if minute.isdigit() and hour.isdigit():
        schedule = {"minutes": [int(minute)], "hours": [int(hour)]}
        if weekday == "*":
            return {**base, "frequency": "Day", "interval": 1, "schedule": schedule}
        chosen: list[int] = []
        for part in weekday.split(","):
            low, _, high = part.partition("-")
            if not low.isdigit() or (high and not high.isdigit()):
                return None
            chosen += list(range(int(low), int(high or low) + 1))
        return {
            **base,
            "frequency": "Week",
            "interval": 1,
            "schedule": {**schedule, "weekDays": [days[d % 7] for d in chosen]},
        }
    if weekday != "*":
        return None
    if minute.isdigit() and hour == "*":
        return {**base, "frequency": "Hour", "interval": 1, "schedule": {"minutes": [int(minute)]}}
    if minute.isdigit() and hour.startswith("*/") and hour[2:].isdigit():
        return {**base, "frequency": "Hour", "interval": int(hour[2:]), "schedule": {"minutes": [int(minute)]}}
    if minute.startswith("*/") and minute[2:].isdigit() and hour == "*":
        return {**base, "frequency": "Minute", "interval": int(minute[2:])}
    return None


