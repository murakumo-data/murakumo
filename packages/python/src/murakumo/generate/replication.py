    def model_why(self, model) -> str:
        entity = model.entity
        parts = [entity.description or ""]
        if model.layer == "staging":
            parts.append(f"A view over the raw `{entity.name}`: each column renamed and given its type, nothing else.")
        elif model.name != entity.name:
            parts.append(f"The rows of {entity.name} before its history is kept: one per key, for the snapshot.")
        elif entity.kind is EntityKind.ACCUMULATING:
            settings = entity.accumulating
            parts.append(
                "An accumulating snapshot: one row per "
                + ", ".join(model.unique_key)
                + ", updated as it passes each milestone ("
                + ", ".join(settings.milestones if settings else [])
                + "). A milestone once reached keeps its date; the time between milestones is computed."
            )
        elif entity.kind is EntityKind.CUMULATIVE:
            parts.append("A cumulative table: one row per key per day, carrying its whole history in arrays.")
        elif model.extra.get("history"):
            parts.append(
                f"Every version of {entity.name} (its SCD4 history): `valid_from`, `valid_to`, and `is_current` "
                "for the latest."
            )
        elif entity.history is History.SCD4:
            parts.append(
                f"The current version of each row (SCD4): `valid_from` says since when. Every version is in "
                f"`{entity.name}_history`."
            )
        elif entity.history in (History.SCD2, History.SCD6):
            parts.append(
                "A dimension with every version of each row (SCD2): `valid_from`, `valid_to`, and `is_current` "
                "for the latest."
            )
            if entity.history is History.SCD6:
                current = [c.name for c in model.columns if c.name.startswith("current_")]
                parts.append("SCD6: every version also has the value as it is now, in " + ", ".join(current) + ".")
        elif entity.history is History.SCD3:
            previous = [c.name for c in model.extra.get("previous", [])]
            parts.append(
                "SCD3: one row per key, with the value before its latest change beside the current one ("
                + ", ".join(previous)
                + "). Incremental, so each run compares what arrives with the row it replaces."
            )
        if model.materialized == "incremental" and entity.kind not in (EntityKind.CUMULATIVE,):
            parts.append(
                "Incremental: built in full the first time, then only the rows loaded since the last run, "
                "replacing the rows with the same key (" + ", ".join(model.unique_key) + ")."
            )
        if model.extra.get("unknown"):
            parts.append("It has an unknown member: a row with key -1 that facts point at when their key is missing.")
        coalesced = [c.name for c in model.columns if c.sql.startswith("coalesce(") and "-1" in c.sql]
        if coalesced and model.layer != "staging":
            parts.append("A missing " + ", ".join(coalesced) + " becomes -1, the dimension's unknown member.")
        if entity.access and model.name == entity.name:
            parts.append(f"Access: {entity.access}.")
        return " ".join(p for p in parts if p)

    def mapping_table(self, model) -> Table | None:
        entity = model.entity
        if model.layer == "staging" or entity.layer is Layer.RAW:
            return None
        mapped = {m.target.lower(): m for m in entity.mappings}
        rows = []
        for column in model.columns:
            mapping = mapped.get(column.name.lower())
            attribute = entity.attribute(column.name)
            rows.append(
                [
                    column.name,
                    column.data_type,
                    ", ".join(mapping.sources) if mapping else "",
                    mapping.expression or "" if mapping else "",
                    (attribute.description if attribute else column.description) or "",
                ]
            )
        return Table(["Column", "Type", "From", "Expression", "Description"], rows)

