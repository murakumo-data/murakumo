"""The replication guide: everything it takes to rebuild the platform by hand, without Murakumo.

``generated/guide/`` holds the guide as numbered chapters (Markdown, and one HTML page), for the
stack chosen, and the SQL it runs, so the platform can be rebuilt from this folder and
``generated/`` alone:

    README.md                  how to use the guide, the chapters, and every step as a checklist
    00-overview.md ...         a chapter per part of the platform, in the order you build it
    index.html                 the whole guide on one page, with the checklist kept in the browser
    sql/build/                 the project as plain SQL: schemas and raw tables, then each model
    sql/load/                  loading the landed files into the raw tables
    sql/tests/                 each test as a query: rows returned are failures
    rebuild.sh                 every script, in order, for the warehouse's own command-line client

Each step says why it is there, gives every command and statement in full, says what you should
see, and has a box to tick. ``murakumo guide --check`` proves the guide is complete: it rebuilds
the project from these scripts alone, on DuckDB, and compares the result with a Murakumo build.
"""

