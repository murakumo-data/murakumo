    # 8. CI/CD -----------------------------------------------------------------------------------

    def cicd(self) -> Chapter:
        from murakumo import ci

        provider = self.manifest.stack.ci
        steps: list[Step] = []
        if provider != "none":
            try:
                path, content = ci.render(
                    self.project, provider, deploy=True, preview=ci.preview_possible(self.project)
                )
            except ci.CIError as exc:
                path, content = None, f"# {exc}"
            parts = ci._deploy_parts(self.project)
            secrets = sorted((parts[1] if parts else {}).values())
            where = ".github/workflows" if provider == "github" else "the repository root"
            steps.append(
                Step(
                    "ci-workflow",
                    "Add the CI workflow",
                    "Each pull request is checked (the model validated, the project built and tested); merging into an "
                    f"environment's branch deploys that environment. Commit it in {where}.",
                    [Block("yaml", content, _from_repository(path) if path else None)],
                    "The workflow's checks on your next pull request.",
                )
            )
            if secrets:
                steps.append(
                    Step(
                        "ci-secrets",
                        "Add the secrets",
                        "The deploy reads its credentials from repository secrets, never from files.",
                        [
                            Block(
                                "bash",
                                "\n".join(f"gh secret set {s}" for s in secrets)
                                if provider == "github"
                                else "# Settings > CI/CD > Variables, masked and protected:\n"
                                + "\n".join(f"# {s}" for s in secrets),
                            )
                        ],
                        "Each secret listed under the repository's secrets.",
                    )
                )
        else:
            steps.append(
                Step(
                    "ci-none",
                    "No CI is chosen",
                    "The stack has `ci: none`. Run `dbt build` against each environment by hand after merging, or "
                    "choose github or gitlab and generate again.",
                )
            )
        return Chapter(
            8, "ci", "CI/CD", "Checking each change, and deploying each environment when its branch changes.", steps
        )

    # 9. Reference -------------------------------------------------------------------------------

    def reference(self) -> Chapter:
        from murakumo import bus, masking

        model = self.project.model
        matrix = bus.bus_matrix(model)
        tables: list[Table] = []
        steps = []
        if matrix.facts and matrix.dimensions:
            head = [
                "Fact (process)",
                "Domain",
                *(d.name + (" (conformed)" if d.conformed else "") for d in matrix.dimensions),
            ]
            rows = [
                [f.name, f.domain or "", *("✓" if d.name in matrix.uses[f.name] else "" for d in matrix.dimensions)]
                for f in matrix.facts
            ]
            steps.append(
                Step(
                    "ref-bus",
                    "The bus matrix",
                    "Which business processes (facts) share which dimensions. A conformed dimension is one table "
                    "every fact that needs it uses, so numbers agree across domains.",
                    tables=[Table(head, rows)],
                )
            )
        steps.append(
            Step("ref-lineage", "Lineage", "Which tables each table is built from.", [Block("mermaid", self.lineage())])
        )
        marts = [m for m in self.plan.models if m.layer not in ("staging", "intermediate") and m.name == m.entity.name]
        for m in marts:
            steps.append(
                Step(
                    f"ref-{m.name}",
                    f"{m.name}",
                    (m.entity.description or "") + (f" Grain: {', '.join(m.entity.grain)}." if m.entity.grain else ""),
                    tables=[self.dictionary(m.entity)],
                )
            )
        if model.exposures:
            tables.append(
                Table(
                    ["Exposure", "Type", "Owner", "Reads", "Link"],
                    [
                        [
                            x.name,
                            x.type,
                            " ".join(p for p in (x.owner, x.email) if p),
                            ", ".join(x.depends_on),
                            x.url or "",
                        ]
                        for x in model.exposures
                    ],
                )
            )
        masked = masking.masked_columns(self.project)
        if masked:
            tables.append(
                Table(
                    ["Column", "Masked because", "Shows"],
                    [[f"{c.entity.name}.{c.column}", c.reason, c.rule] for c in masked],
                )
            )
        return Chapter(
            9,
            "reference",
            "Reference",
            "The data dictionary of every mart, the bus matrix, lineage, the dashboards and apps that read the "
            "marts, and what is masked.",
            steps,
            tables=tables,
        )

    def lineage(self) -> str:
        lines = ["flowchart LR"]
        seen = set()
        for model in self.plan.models + self.plan.snapshots:
            text = model.relation + " " + " ".join(j.relation for j in getattr(model, "joins", []))
            for ref in re.findall(r"ref\('([^']+)'\)", text):
                lines.append(f"  {ref} --> {model.name}")
                seen.add(ref)
            for _group, table in re.findall(r"source\('([^']+)', '([^']+)'\)", text):
                lines.append(f"  raw_{table}[({table})] --> {model.name}")
        for exposure in self.project.model.exposures:
            for name in exposure.depends_on:
                lines.append(f'  {name} --> x_{exposure.name}["{exposure.name}"]')
        return "\n".join(lines)

