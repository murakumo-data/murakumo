def _from_repository(path: Path) -> str:
    """The workflow's path from the repository root, so the guide is the same on every machine."""
    parts = path.parts
    for start in (".github", ".gitlab-ci.yml"):
        if start in parts:
            return "/".join(parts[parts.index(start) :])
    return path.name
