    def dictionary(self, entity) -> Table:
        rows = []
        keys = {a.name for a in entity.primary_key}
        for a in entity.attributes:
            notes = []
            if a.name in keys:
                notes.append("primary key")
            if a.pii:
                notes.append("PII")
            if a.classification:
                notes.append(a.classification.value)
            if a.accepted_values:
                notes.append("one of " + ", ".join(sorted(a.accepted_values)))
            rows.append(
                [
                    a.name,
                    f"{a.type} ({self.plan.target.physical(a.logical_type)})",
                    "yes" if a.nullable else "no",
                    a.description or "",
                    "; ".join(notes),
                ]
            )
        return Table(["Column", "Type", "Nullable", "Description", "Notes"], rows)

