    def try_by_hand(self, connection) -> str:
        kind = connection.kind
        if kind == "rest":
            auth = connection.auth
            headers = [f"-H '{k}: {v}'" for k, v in connection.headers.items()]
            query = ""
            if auth.type == "bearer":
                headers.append(f'-H "Authorization: Bearer ${auth.env}"')
            elif auth.type == "api_key" and auth.location == "header":
                headers.append(f'-H "{auth.name}: ${auth.env}"')
            elif auth.type == "api_key":
                query = f"{auth.name}=${auth.env}"
            elif auth.type == "basic":
                headers.append(f'-u "${auth.user_env}:${auth.password_env}"')
            lines = []
            if auth.type == "oauth2":
                lines.append(
                    f'TOKEN=$(curl -sS -u "${auth.client_id_env}:${auth.client_secret_env}" '
                    f"-d grant_type=client_credentials {('-d scope=' + auth.scope + ' ') if auth.scope else ''}"
                    f"'{auth.token_url}' | python3 -c 'import json,sys; print(json.load(sys.stdin)[\"access_token\"])')"
                )
                headers.append('-H "Authorization: Bearer $TOKEN"')
            for endpoint in connection.endpoints:
                params = "&".join(f"{k}={v}" for k, v in endpoint.params.items())
                params = "&".join(p for p in (params, query) if p)
                url = (
                    connection.base_url.rstrip("/") + "/" + endpoint.path.lstrip("/") + (f"?{params}" if params else "")
                )
                lines.append(f"# {endpoint.table}: the records are at {endpoint.records or 'the top of the response'}")
                lines.append(f'curl -sS {" ".join(headers)} "{url}" | head -c 2000; echo')
            return "\n".join(lines)
        if kind == "sftp":
            key = f' -i "${connection.key_file_env}"' if connection.key_file_env else ""
            login = f'"${connection.user_env}@{connection.host}"'
            return f'echo "ls {connection.path}" | sftp -P {connection.port}{key} {login}'
        if kind == "database":
            first = connection.tables[0].source if connection.tables else "information_schema.tables"
            query = first if first.lower().startswith("select") else f"select * from {first}"
            return (
                "pip install sqlalchemy\n"
                f"python3 -c \"import os, sqlalchemy as sa; e = sa.create_engine(os.environ['{connection.url_env}']); "
                f"print(e.connect().execute(sa.text('{query} limit 5')).fetchall())\""
            )
        location = connection.location
        if "://" in location:
            return f"aws s3 ls {location.rstrip('/')}/"
        return f"ls -la {location}"

