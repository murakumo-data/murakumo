    def diagram(self) -> str:
        stack = self.manifest.stack
        lines = ["flowchart LR"]
        sources = [g.name for g in self.plan.sources]
        for name in sources:
            lines.append(f"  src_{name}[({name})]")
        extract = {"python": "extract.py", "lambda": "AWS Lambda", "glue": "AWS Glue", "none": "your loader"}[
            stack.extract
        ]
        load = {"build": "load SQL", "snowpipe": "Snowpipe", "autoloader": "Auto Loader"}[stack.load]
        lines += [
            f'  extract["{extract}"]',
            f'  landing[/"landing: {stack.landing}"/]',
            f'  load["{load}"]',
            '  raw[("raw tables")]',
            '  staging["staging views"]',
            '  marts[("marts: facts and dimensions")]',
        ]
        for name in sources:
            lines.append(f"  src_{name} --> extract")
        lines += ["  extract --> landing --> load --> raw --> staging"]
        if any(m.layer == "intermediate" for m in self.plan.models) or self.plan.snapshots:
            lines += ['  intermediate["intermediate and snapshots"]', "  staging --> intermediate --> marts"]
        else:
            lines.append("  staging --> marts")
        for exposure in self.project.model.exposures:
            lines += [f'  x_{exposure.name}["{exposure.name} ({exposure.type})"]', f"  marts --> x_{exposure.name}"]
        orchestrator = self.manifest.generation.orchestrator.value
        lines += [
            f'  orch{{{{"{orchestrator}"}}}}',
            "  orch -.runs.-> extract",
            "  orch -.runs.-> load",
            "  orch -.runs.-> staging",
        ]
        return "\n".join(lines)

