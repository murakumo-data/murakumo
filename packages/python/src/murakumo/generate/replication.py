def page(chapters: list[Chapter], project: Project) -> str:
    name = project.manifest.project.name
    nav = "".join(f'<a href="#ch{c.number}">{c.number}. {html.escape(c.title)}</a>' for c in chapters)
    body = []
    for chapter in chapters:
        body.append(f'<h2 id="ch{chapter.number}">{chapter.number}. {html.escape(chapter.title)}</h2>')
        body.append(_paragraphs(chapter.intro))
        body += [_html_table(t) for t in chapter.tables]
        for index, step in enumerate(chapter.steps, start=1):
            number = f"{chapter.number}.{index}"
            body.append(f'<h3 id="{step.key}">{number} {html.escape(step.title)}</h3>')
            body.append(f"<p><strong>Why:</strong> {_inline(step.why.strip())}</p>")
            body += [_html_table(t) for t in step.tables]
            for block in step.blocks:
                if block.title:
                    body.append(f'<div class="block-title">{_inline(block.title)}</div>')
                body.append(f'<pre><code class="{block.lang}">{html.escape(block.text.rstrip())}</code></pre>')
            if step.expect:
                body.append(f'<p class="expect"><strong>You should see:</strong> {_inline(step.expect.strip())}</p>')
            body.append(
                f'<label class="done"><input type="checkbox" data-step="{step.key}"> '
                f"Done: {html.escape(step.title)}</label>"
            )
    intro = _paragraphs(
        "Everything it takes to build this data platform yourself, without Murakumo, in order. Tick each "
        "step as you go: the ticks stay in this browser. The scripts are in `sql/`, beside this page."
    )
    return _PAGE.format(name=html.escape(name), nav=nav, intro=intro, body="\n".join(body), version=__version__)


# Writing the chapters ----------------------------------------------------------------------------


class Writer:
    def __init__(self, project: Project, plan: Plan, files: dict[str, str]):
        from murakumo.generate import export_sql
        from murakumo.generate import loads as load_scripts

        self.project = project
        self.plan = plan
        self.files = files
        self.manifest = project.manifest
        self.warehouse = plan.target.warehouse
        self.wh = self.warehouse.value
        self.duckdb = self.warehouse is Warehouse.DUCKDB
        self.snowflake = self.warehouse is Warehouse.SNOWFLAKE
        self.plain = export_sql(plan, files)
        self.loads = load_scripts.render(plan)
        self.load_tables = load_scripts.tables(plan)
        from murakumo.generate.verify import _duckdb_path

        self.database = _duckdb_path(project).name if self.duckdb else None

    # helpers --------------------------------------------------------------------------------

    def run_file(self, path: str) -> str:
        """The command that runs a SQL file in the warehouse's own client, from the project folder."""
        if self.duckdb:
            return f"duckdb {self.database} < {path}"
        if self.snowflake:
            return f"snow sql -f {path}"
        return f"# run {path} in your {self.wh} client"

    def client(self) -> str:
        return {
            Warehouse.DUCKDB: "the DuckDB command-line client (`duckdb`, 1.1 or later)",
            Warehouse.SNOWFLAKE: "the Snowflake CLI (`snow`), or SnowSQL, connected with the variables in chapter 1",
        }.get(self.warehouse, f"your {self.wh} SQL client")

    def guide_path(self, path: str) -> str:
        return f"generated/{FOLDER}/{path}"

