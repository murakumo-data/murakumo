"""The pipeline as Python: PySpark or Polars jobs, from the same SQL as the dbt project.

``generate`` writes them to ``generated/python/<engine>/`` when ``generation.python_engine`` is
pyspark or polars:

    runtime.py         reads raw tables, builds models, keeps incremental, cumulative and snapshot
                       tables up to date, runs the tests and writes the audit tables
    project.json       the raw tables and their columns, and what each schedule builds
    models/NN_name.py  one module per model, in the order they run, with its SQL and its tests
    run.py             runs everything, or one schedule: python run.py --schedule nightly

Each model's SQL is its dbt SQL rendered once more with the runtime's own ``source()``, ``ref()``
and ``this`` (as the plain-SQL export does), in Spark SQL for PySpark and DuckDB SQL for Polars.
"""

from __future__ import annotations

import json
from importlib import resources

from murakumo.generate import dbt
from murakumo.generate.plain import Plain
from murakumo.generate.plan import build_plan, quote_identifier
from murakumo.generate.targets import target_for
from murakumo.manifest import Warehouse

ENGINES = {"polars": (Warehouse.DUCKDB, "duckdb"), "pyspark": (Warehouse.DATABRICKS, "spark")}
RUN_DATE = "__MURAKUMO_RUN_DATE__"
HEADER = '"""Generated by Murakumo. Do not edit: change the model, then run `murakumo generate`.\n\n{doc}\n"""\n'


class Flat(Plain):
    """Plain SQL whose tables are the runtime's views: schema__table."""

    def __init__(self, plan, files, dialect: str):
        super().__init__(plan, files)
        self.out = dialect
        self.variables = {"run_date": RUN_DATE}

    def view_name(self, schema: str, name: str) -> str:
        return f"{schema}__{name}".lower()

    def relation(self, name: str) -> str:
        return self.view_name(self.schemas[name], name)

    def source(self, group: str, table: str) -> str:
        return self.view_name(self.groups[group], table)

    def sql(self, text: str) -> str:
        import sqlglot

        return ";\n".join(sqlglot.transpile(text, read="duckdb", write=self.out, pretty=True))

    def query(self, test_sql: str) -> str:
        """A test's query without its comment and semicolon."""
        lines = [line for line in test_sql.strip().splitlines() if not line.startswith("--")]
        return "\n".join(lines).rstrip(";").strip()


def _literal(text: str) -> str:
    """A Python string literal that reads well for SQL: triple-quoted when it spans lines."""
    if "\n" in text and '"""' not in text and not text.endswith('"'):
        return '"""\n' + text.replace("\\", "\\\\") + '\n"""'
    return json.dumps(text)


def _module(flat: Flat, kind: str, node, position: int) -> tuple[str, str]:
    schema = flat.schemas[node.name]
    view = flat.view_name(schema, node.name)
    q = lambda name: quote_identifier(name, flat.out if flat.out != "spark" else "databricks")  # noqa: E731
    tests = []
    if kind == "model":
        for test in [*(t for c in node.columns for t in c.tests), *node.tests]:
            text = flat.test(node.name, test)
            if text.startswith("-- ") and "no plain SQL form" in text:
                continue
            tests.append((test.name, test.column, flat.query(text), test.severity))
    lines = [f'NAME = "{node.name}"', f'SCHEMA = "{schema}"', f'VIEW = "{view}"']
    if kind == "snapshot":
        source = flat.relation(node.relation.split("'")[1])
        keys = [q(k) for k in node.unique_key]
        columns = [q(c.name) for c in node.columns]
        lines += [
            'KIND = "snapshot"',
            f"SOURCE = {json.dumps(source)}",
            f"KEYS = {json.dumps(keys)}",
            f"COLUMNS = {json.dumps(columns)}",
            "",
            "",
            "def build(ctx):",
            "    ctx.snapshot(NAME, SCHEMA, VIEW, SOURCE, KEYS, COLUMNS)",
        ]
        doc = f"{node.name}: every version of {node.entity.name if node.entity else node.name} (SCD2)."
    elif node.materialized == "incremental":
        lines += [
            'KIND = "incremental"',
            f"FULL = {_literal(flat.select(node))}",
            f"NEW_ROWS = {_literal(flat.select(node, incremental=True))}",
            f"KEYS = {json.dumps([q(k) for k in node.unique_key])}",
            "",
            "",
            "def build(ctx):",
            "    ctx.incremental(NAME, SCHEMA, VIEW, FULL, NEW_ROWS, KEYS)",
        ]
        doc = f"{node.name} ({node.layer}, incremental): {node.description or ''}".rstrip(": ")
    else:
        materialized = "view" if node.materialized == "view" else "table"
        lines += [
            f'KIND = "{materialized}"',
            f"QUERY = {_literal(flat.select(node))}",
            "",
            "",
            "def build(ctx):",
            f"    ctx.{materialized}(NAME, SCHEMA, VIEW, QUERY)",
        ]
        doc = f"{node.name} ({node.layer}, {materialized}): {node.description or ''}".rstrip(": ")
    test_lines = ["TESTS = ["]
    for name, column, query, severity in tests:
        column_literal = "None" if column is None else json.dumps(column)
        test_lines.append(f"    ({json.dumps(name)}, {column_literal}, {_literal(query)}, {json.dumps(severity)}),")
    test_lines.append("]")
    body = "\n".join(lines[:4] + test_lines + lines[4:]) + "\n"
    return f"models/{position:02d}_{node.name}.py", HEADER.format(doc=doc) + "\n" + body


def render(project, engine: str) -> dict[str, str]:
    """The files of the Python pipeline for one engine."""
    from murakumo.schedules import ScheduleError, dbt_models, resolve

    warehouse, dialect = ENGINES[engine]
    plan = build_plan(project, target_for(warehouse))
    flat = Flat(plan, dbt.render(plan), dialect)
    files: dict[str, str] = {"models/__init__.py": ""}
    for position, (kind, node) in enumerate(flat.order(), start=1):
        path, content = _module(flat, kind, node, position)
        files[path] = content
    try:
        schedules = {entry.schedule.name: dbt_models(plan, entry.entities) for entry in resolve(project)}
    except ScheduleError:
        schedules = {}
    config = {
        "project": project.manifest.project.name,
        "engine": engine,
        "raw": [
            {
                "view": flat.view_name(group.schema, table.entity.name),
                "schema": group.schema,
                "table": table.entity.name,
                "source": group.name,
                "columns": [a.name for a in table.entity.attributes],
            }
            for group in plan.sources
            for table in group.tables
        ],
        "schedules": schedules,
    }
    files["project.json"] = json.dumps(config, indent=2) + "\n"
    template = resources.files("murakumo.generate").joinpath("templates/python")
    files["runtime.py"] = template.joinpath("runtime.py").read_text(encoding="utf-8")
    files["run.py"] = template.joinpath("run.py").read_text(encoding="utf-8").replace("__ENGINE__", engine)
    files["requirements.txt"] = (
        "pyspark>=3.5,<4\njdk4py>=21,<22  # a Java runtime for Spark, if the machine has none\n"
        "delta-spark>=3.2,<4  # for --format delta\n"
        "duckdb>=1.1\npolars>=1.0\npandas\npyarrow\n"
        if engine == "pyspark"
        else "polars>=1.0\nduckdb>=1.1\npyarrow\n"
    )
    files["README.md"] = _readme(project, engine, len(flat.order()), schedules)
    return files


def _readme(project, engine: str, models: int, schedules: dict[str, list[str]]) -> str:
    name = project.manifest.project.name
    how = (
        "Spark SQL over temporary views; tables are written as Parquet (or Delta with `--format delta` and "
        "`delta-spark` installed)"
        if engine == "pyspark"
        else "Polars data frames, each model's SQL run by DuckDB over them; tables are written as Parquet"
    )
    listed = "\n".join(f"- `{s}`: {len(m)} model(s)" for s, m in schedules.items())
    return (
        f"# {name} as a {engine} pipeline\n\n"
        f"{models} models, from the same SQL as the dbt project in `generated/dbt`: {how}.\n\n"
        "```bash\n"
        "pip install -r requirements.txt\n"
        "python run.py --duckdb ../../../"
        + f"{name}.duckdb --output ../../../lake       # raw tables from the DuckDB file\n"
        "python run.py --data orders=orders.parquet --output lake          # or from files\n"
        "python run.py --schedule nightly --run-date 2024-01-31 ...         # one schedule, one day\n"
        "```\n\n"
        "Tables go to `<output>/<schema>/<table>`; incremental, cumulative and snapshot tables are read back\n"
        "from there on the next run. Every run is recorded in `<output>/audit/`: `run_log`, `model_runs`,\n"
        "`dq_results` and `row_counts`, as the dbt project records them in the warehouse.\n\n"
        f"Schedules:\n\n{listed}\n\n"
        "`murakumo run --engine "
        + engine
        + "` runs this from the project, with made-up rows if you like (`--sample`).\n"
    )


__all__ = ["ENGINES", "render"]
