"""Streaming: Kafka topics into the raw tables, by ``streaming.engine``.

- ``consumer`` (the default): the extract script reads each topic since its last commit and lands
  the messages as files, on each schedule (or as often as the orchestrator runs it).
- ``flink``: a Flink SQL job per source reads each topic continuously and writes the messages as
  JSON files into the landing area, a file a minute.
- ``spark``: the same as a Spark Structured Streaming job (``--sink table`` writes straight into the
  raw Delta table instead, on Databricks).
- ``snowpipe_streaming``: the Snowflake Kafka connector (in Kafka Connect) writes each topic into
  its raw table within seconds, through Snowpipe Streaming.

Flink and Spark land files where the loads look for them, so loading stays the stack's choice
(each build, Snowpipe or Auto Loader). ``generated/streaming/docker-compose.yml`` starts Redpanda
(Kafka's protocol) and Flink on this computer.
"""

from __future__ import annotations

import json

from murakumo.generate.plan import Plan, snake

FOLDER = "streaming"
ENGINES = ("consumer", "flink", "spark", "snowpipe_streaming")

_FLINK_TYPES = {
    "text": "STRING",
    "integer": "BIGINT",
    "boolean": "BOOLEAN",
    "date": "DATE",
    "timestamp": "TIMESTAMP(3)",
}
_SPARK_TYPES = {
    "text": "StringType()",
    "integer": "LongType()",
    "boolean": "BooleanType()",
    "date": "DateType()",
    "timestamp": "TimestampType()",
}


def kafka_sources(project) -> list:
    from murakumo.generate.ingestion import connected

    return [d for d in connected(project) if d.connection.kind == "kafka"]  # type: ignore[union-attr]


def landing_glob(table: str) -> str:
    """What the loads read in a Kafka table's landing folder: every file but the engines' own
    (in-progress files start with a dot, Spark's log with an underscore)."""
    return "[!._]*"


def _flink_type(attribute) -> str:
    logical = attribute.logical_type
    if logical.family == "number":
        return f"DECIMAL({logical.precision or 38}, {logical.scale or 0})" if logical.precision else "DOUBLE"
    if logical.family == "timestamp" and str(logical).endswith("_tz"):
        return "TIMESTAMP_LTZ(3)"
    return _FLINK_TYPES.get(logical.family, "STRING")


def _spark_type(attribute) -> str:
    logical = attribute.logical_type
    if logical.family == "number":
        return f"DecimalType({logical.precision}, {logical.scale or 0})" if logical.precision else "DoubleType()"
    return _SPARK_TYPES.get(logical.family, "StringType()")


def _tables(plan: Plan, declaration):
    from murakumo.generate.ingestion import _raw_tables

    raw = _raw_tables(plan)
    for topic in declaration.connection.topics:
        found = raw.get(topic.table)
        if found is not None:
            yield topic, found[1]


def _flink(project, plan: Plan, declaration) -> str:
    c = declaration.connection
    landing = project.manifest.stack.landing.rstrip("/")
    group = c.group or f"murakumo-{declaration.name}"
    # A local landing folder is the project's, which the containers mount at /project.
    where = landing if "://" in landing else f"file:///project/{landing}"
    lines = [
        f"-- Generated by Murakumo: stream {declaration.name}'s topics into {landing}, as JSON files.",
        "-- Run with the Flink SQL client: sql-client.sh -f " + f"{declaration.name}.sql",
        "-- Each checkpoint finishes the files written since the last one.",
        "SET 'execution.checkpointing.interval' = '1 min';",
        f"SET 'pipeline.name' = 'murakumo-{declaration.name}';",
        "",
    ]
    for topic, entity in _tables(plan, declaration):
        columns = ",\n".join(f"  `{a.name}` {_flink_type(a)}" for a in entity.attributes)
        source, sink = f"{topic.table}_topic", f"{topic.table}_landing"
        properties = [
            ("connector", "kafka"),
            ("topic", topic.topic),
            ("properties.bootstrap.servers", c.bootstrap_servers),
            ("properties.group.id", f"{group}-{topic.table}"),
            ("properties.security.protocol", c.security_protocol),
            ("scan.startup.mode", "group-offsets"),
            ("properties.auto.offset.reset", "earliest"),
            ("format", "json"),
            ("json.ignore-parse-errors", "true"),
            ("json.timestamp-format.standard", "ISO-8601"),
        ]
        if c.sasl_mechanism:
            properties.append(("properties.sasl.mechanism", c.sasl_mechanism))
            properties.append(
                (
                    "properties.sasl.jaas.config",
                    "org.apache.kafka.common.security.plain.PlainLoginModule required "
                    f'username="${{{c.username_env}}}" password="${{{c.password_env}}}";',
                )
            )
        lines += [
            f"CREATE TABLE IF NOT EXISTS {source} (\n{columns}\n) WITH (",
            ",\n".join(f"  '{k}' = '{v}'" for k, v in properties),
            ");",
            "",
            f"CREATE TABLE IF NOT EXISTS {sink} (\n{columns}\n) WITH (",
            "  'connector' = 'filesystem',",
            f"  'path' = '{where}/{declaration.name}/{topic.table}',",
            "  'format' = 'json',",
            "  'sink.rolling-policy.rollover-interval' = '1 min',",
            "  'sink.rolling-policy.check-interval' = '10 s'",
            ");",
            "",
            f"INSERT INTO {sink} SELECT * FROM {source};",
            "",
        ]
    return "\n".join(lines)


def _spark(project, plan: Plan, declaration) -> str:
    c = declaration.connection
    landing = project.manifest.stack.landing.rstrip("/")
    tables = []
    for topic, entity in _tables(plan, declaration):
        fields = ", ".join(f'StructField("{a.name}", {_spark_type(a)})' for a in entity.attributes)
        tables.append(
            f'    "{topic.table}": ("{topic.topic}", "raw_{snake(declaration.name)}.{topic.table}", '
            f"StructType([{fields}])),"
        )
    options = {"kafka.bootstrap.servers": c.bootstrap_servers, "kafka.security.protocol": c.security_protocol}
    sasl = ""
    if c.sasl_mechanism:
        sasl = (
            f'\n    options["kafka.sasl.mechanism"] = "{c.sasl_mechanism}"\n'
            '    options["kafka.sasl.jaas.config"] = (\n'
            '        "org.apache.kafka.common.security.plain.PlainLoginModule required "\n'
            f'        f\'username="{{os.environ["{c.username_env}"]}}" \'\n'
            f'        f\'password="{{os.environ["{c.password_env}"]}}";\'\n'
            "    )"
        )
    return f'''"""Generated by Murakumo: stream {declaration.name}'s Kafka topics with Spark Structured Streaming.

    spark-submit --packages org.apache.spark:spark-sql-kafka-0-10_2.12:3.5.5 {declaration.name}.py
    spark-submit ... {declaration.name}.py --sink table    # Databricks: straight into the raw tables

Each topic's messages land as JSON files in {landing}/{declaration.name}/<table>/ (or are appended to
the raw table), a micro-batch a minute; the checkpoint remembers where each topic got to.
"""

import argparse
import os

from pyspark.sql import SparkSession
from pyspark.sql.functions import col, current_timestamp, from_json, lit
from pyspark.sql.types import (  # noqa: F401
    BooleanType, DateType, DecimalType, DoubleType, LongType, StringType, StructField, StructType, TimestampType,
)

TABLES = {{
{chr(10).join(tables)}
}}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sink", choices=["landing", "table"], default="landing")
    parser.add_argument("--landing", default=os.environ.get("MURAKUMO_LANDING", {json.dumps(landing)}))
    parser.add_argument("--checkpoints", default=os.environ.get("MURAKUMO_CHECKPOINTS", "checkpoints"))
    parser.add_argument("--once", action="store_true", help="read what is there now, then stop")
    args = parser.parse_args()
    spark = SparkSession.builder.appName("murakumo-{declaration.name}").getOrCreate()
    options = {json.dumps(options)}{sasl}
    queries = []
    for table, (topic, raw_table, schema) in TABLES.items():
        stream = (
            spark.readStream.format("kafka")
            .options(**options)
            .option("subscribe", topic)
            .option("startingOffsets", "earliest")
            .load()
            .select(from_json(col("value").cast("string"), schema).alias("message"))
            .select("message.*")
        )
        trigger = {{"availableNow": True}} if args.once else {{"processingTime": "1 minute"}}
        checkpoint = f"{{args.checkpoints}}/{declaration.name}/{{table}}"
        if args.sink == "table":
            stream = stream.withColumn("_ingested_at", current_timestamp())
            stream = stream.withColumn("_batch_id", lit(None).cast("string"))
            query = stream.writeStream.option("checkpointLocation", checkpoint).trigger(**trigger).toTable(raw_table)
        else:
            query = (
                stream.writeStream.format("json")
                .option("path", f"{{args.landing}}/{declaration.name}/{{table}}")
                .option("checkpointLocation", checkpoint)
                .trigger(**trigger)
                .start()
            )
        queries.append(query)
    for query in queries:
        query.awaitTermination()


if __name__ == "__main__":
    main()
'''


def _snowpipe_streaming(project, plan: Plan, declaration) -> str:
    from murakumo.generate.dbt import warehouse_database

    c = declaration.connection
    database = warehouse_database(project.manifest).upper()
    topics = list(_tables(plan, declaration))
    config = {
        "name": f"murakumo-{declaration.name}-snowflake",
        "config": {
            "connector.class": "com.snowflake.kafka.connector.SnowflakeSinkConnector",
            "tasks.max": "1",
            "topics": ",".join(t.topic for t, _ in topics),
            "snowflake.topic2table.map": ",".join(f"{t.topic}:{t.table.upper()}" for t, _ in topics),
            "snowflake.ingestion.method": "SNOWPIPE_STREAMING",
            "snowflake.enable.schematization": "true",
            "snowflake.url.name": "${env:SNOWFLAKE_ACCOUNT}.snowflakecomputing.com:443",
            "snowflake.user.name": "${env:SNOWFLAKE_USER}",
            "snowflake.private.key": "${env:SNOWFLAKE_PRIVATE_KEY}",
            "snowflake.role.name": "${env:SNOWFLAKE_ROLE_PROD}",
            "snowflake.database.name": database,
            "snowflake.schema.name": f"RAW_{snake(declaration.name).upper()}",
            "buffer.flush.time": "10",
            "key.converter": "org.apache.kafka.connect.storage.StringConverter",
            "value.converter": "org.apache.kafka.connect.json.JsonConverter",
            "value.converter.schemas.enable": "false",
            "errors.tolerance": "all",
            "errors.deadletterqueue.topic.name": f"{declaration.name}_dead_letters",
        },
    }
    if c.bootstrap_servers:
        config["config"]["bootstrap.servers"] = c.bootstrap_servers
    return json.dumps(config, indent=2) + "\n"


