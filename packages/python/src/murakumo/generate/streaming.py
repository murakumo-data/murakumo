def render(project, plan: Plan) -> dict[str, str]:
    sources = kafka_sources(project)
    engine = project.manifest.generation.streaming.engine
    if not sources or engine == "consumer":
        return {}
    files: dict[str, str] = {}
    for declaration in sources:
        if engine == "flink":
            files[f"{FOLDER}/flink/{declaration.name}.sql"] = _flink(project, plan, declaration)
        elif engine == "spark":
            files[f"{FOLDER}/spark/{declaration.name}.py"] = _spark(project, plan, declaration)
        elif engine == "snowpipe_streaming":
            files[f"{FOLDER}/kafka-connect/{declaration.name}.json"] = _snowpipe_streaming(project, plan, declaration)
    if engine == "flink":
        files[f"{FOLDER}/docker-compose.yml"] = COMPOSE
        files[f"{FOLDER}/flink-jars.sh"] = JARS
    files[f"{FOLDER}/README.md"] = _readme(project, engine, sources)
    return files


def _readme(project, engine: str, sources) -> str:
    names = ", ".join(d.name for d in sources)
    how = {
        "flink": [
            "```bash",
            "docker compose -f generated/streaming/docker-compose.yml up -d",
            "bash generated/streaming/flink-jars.sh",
            *(
                "docker compose -f generated/streaming/docker-compose.yml exec jobmanager \\\n"
                f"  ./bin/sql-client.sh -j /opt/flink/usrlib/flink-sql-connector-kafka.jar "
                f"-f /project/generated/streaming/flink/{d.name}.sql"
                for d in sources
            ),
            "```",
            "",
            "The landing path in each job is the project's landing area; inside the containers the project",
            "is mounted at /project, so a local landing folder is written as /project/<folder>.",
        ],
        "spark": [
            "```bash",
            *(
                "spark-submit --packages org.apache.spark:spark-sql-kafka-0-10_2.12:3.5.5 "
                f"generated/streaming/spark/{d.name}.py"
                for d in sources
            ),
            "```",
        ],
        "snowpipe_streaming": [
            "Install the Snowflake Kafka connector in Kafka Connect, then add each connector:",
            "",
            "```bash",
            *(
                "curl -X POST -H 'Content-Type: application/json' "
                f"--data @generated/streaming/kafka-connect/{d.name}.json http://localhost:8083/connectors"
                for d in sources
            ),
            "```",
        ],
    }[engine]
    return "\n".join([f"# Streaming ({engine})", "", f"The Kafka sources: {names}.", "", *how]) + "\n"


