"""The platform as Terraform (``stack.iac: terraform``), beside the SQL and scripts Murakumo writes.

    terraform/snowflake/   the warehouse, its spending cap, a database per environment, and roles
    terraform/aws/         the landing bucket, the extract functions or Glue jobs, Snowpipe's role
    terraform/databricks/  a catalog per environment, its groups and grants, a SQL warehouse

Roles follow Snowflake's guidance: **access roles** hold the privileges on one database
(``<DB>_READ``, ``<DB>_WRITE``), and **functional roles** are what people and CI use (the
developer role, each environment's deployer, the roles that see personal data), made of access
roles. The provisioning SQL (``murakumo env provision``) creates the same roles.

The AWS module takes an ``endpoint`` variable: set it to a local AWS (LocalStack's
``http://localhost:4566``) to try everything without an AWS account.

Credentials are never in these files: the providers read them from the environment
(``SNOWFLAKE_*``, ``AWS_*``, ``DATABRICKS_*``), and source secrets are sensitive variables.
"""

