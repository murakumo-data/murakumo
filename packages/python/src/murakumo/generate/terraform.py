def _hcl(value: Any) -> str:
    """A Terraform value, on one line: strings, numbers, booleans, null, lists and maps."""
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = ", ".join(f"{_key(k)} = {_hcl(v)}" for k, v in value.items())
        return "{ " + items + " }"
    if isinstance(value, list | tuple):
        return "[" + ", ".join(_hcl(v) for v in value) + "]"
    if value is None:
        return "null"
    return json.dumps(value)


def _key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_-]*", key) else json.dumps(key)


_ATTRIBUTE = re.compile(r"^(\s*)([A-Za-z_][\w-]*|\"[^\"]+\"|\([^)]*\))\s*=\s*(.*)$")


def fmt(text: str) -> str:
    """Align the = of adjacent one-line attributes, as `terraform fmt` does."""
    lines = text.split("\n")
    out: list[str] = []
    group: list[tuple[str, str, str]] = []

    def flush() -> None:
        width = max((len(k) for _, k, _ in group), default=0)
        out.extend(f"{indent}{key.ljust(width)} = {value}" for indent, key, value in group)
        group.clear()

    for line in lines:
        match = _ATTRIBUTE.match(line)
        if match and not line.lstrip().startswith("#"):
            indent, key, value = match.groups()
            if group and group[0][0] != indent:
                flush()
            if value.rstrip().endswith(("{", "[", "(")):
                flush()  # its value goes on over lines: it is not aligned, and ends the group
                out.append(f"{indent}{key} = {value}")
                continue
            group.append((indent, key, value))
            continue
        flush()
        out.append(line)
    flush()
    return "\n".join(out)


def _versions(*providers: str) -> str:
    lines = ["terraform {", '  required_version = ">= 1.5"', "  required_providers {"]
    for name in providers:
        source, version = VERSIONS[name]
        lines.append(f'    {name} = {{ source = "{source}", version = "{version}" }}')
    lines += ["  }", "}", ""]
    return HEADER + "\n".join(lines)


def roles(project) -> dict[str, Any]:
    """The access and functional roles, as the provisioning SQL and Terraform both create them."""
    from murakumo.generate.dbt import warehouse_database

    manifest = project.manifest
    name = manifest.project.name.upper()
    default = warehouse_database(manifest).upper()
    personal = (manifest.collaboration.personal_database or default).upper()
    databases: dict[str, list[str]] = {}
    for env in manifest.targets.environments:
        databases.setdefault((env.database or default).upper(), []).append(env.name)
    last = (manifest.targets.environments[-1].database or default).upper() if manifest.targets.environments else default
    return {
        "name": name,
        "personal": personal,
        "developer": f"{name}_DEVELOPER",
        "databases": databases,
        "deployers": {
            env.name: (f"{name}_DEPLOYER_{env.name.upper()}", (env.database or default).upper())
            for env in manifest.targets.environments
        },
        "unmasked": [r.upper() for r in manifest.governance.unmasked_roles],
        "production": last,
    }


