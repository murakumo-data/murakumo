def modules(project) -> list[str]:
    """Which Terraform modules the stack needs, in the order to apply them."""
    manifest = project.manifest
    if manifest.stack.iac != "terraform":
        return []
    stack = manifest.stack
    warehouse = manifest.targets.warehouse.type
    out = []
    if warehouse is Warehouse.SNOWFLAKE:
        out.append("snowflake")
    if warehouse is Warehouse.DATABRICKS:
        out.append("databricks")
    if stack.landing.startswith("s3://") or stack.extract in ("lambda", "glue") or stack.load == "snowpipe":
        out.append("aws")
    return out


def render(project, plan) -> dict[str, str]:
    chosen = modules(project)
    files: dict[str, str] = {}
    if "snowflake" in chosen:
        files.update(_snowflake(project))
    if "databricks" in chosen:
        files.update(_databricks(project))
    if "aws" in chosen:
        files.update(_aws(project, plan))
    files = {path: fmt(text) for path, text in files.items()}
    if files:
        files[f"{FOLDER}/README.md"] = _readme(chosen)
        files[f"{FOLDER}/.gitignore"] = ".terraform/\n*.tfstate\n*.tfstate.*\n*.tfvars\n.build/\n"
    return files


def _readme(chosen: list[str]) -> str:
    lines = [
        "# The platform as Terraform",
        "",
        "Generated by Murakumo from `murakumo.yaml` (`stack.iac: terraform`). Apply each module, in this order:",
        "",
    ]
    what = {
        "snowflake": "the compute warehouse and its spending cap, a database per environment, the access roles "
        "(`<DB>_READ`, `<DB>_WRITE`) and the functional roles made of them",
        "databricks": "a catalog per environment, the groups and their grants, and a serverless SQL warehouse",
        "aws": "the landing bucket, and what fetches into it or loads from it",
    }
    for index, module in enumerate(chosen, start=1):
        lines.append(f"{index}. `{module}/`: {what[module]}.")
    lines += [
        "",
        "```bash",
        *(f"terraform -chdir={m} init && terraform -chdir={m} apply" for m in chosen),
        "```",
        "",
        "The providers read credentials from the environment, never from these files. Keep the state",
        "somewhere shared (a `backend` block) once more than one person applies it.",
    ]
    if "aws" in chosen:
        lines += [
            "",
            "To try the AWS module without an AWS account, on LocalStack:",
            "",
            "```bash",
            "docker run -d -p 4566:4566 localstack/localstack",
            "AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test \\",
            "  terraform -chdir=aws apply -var endpoint=http://localhost:4566",
            "```",
        ]
    return "\n".join(lines) + "\n"


